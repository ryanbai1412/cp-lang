WORDS = [SCRAMBLE[i:i + 5] for i in range(0, len(SCRAMBLE), 5)]
VALID = set(WORDS)
POINTS = [150, 120, 100, 90, 85]


def marks(guess, answer):
    gold = [guess[k] == answer[k] for k in range(5)]
    rest = [answer[l] for l in range(5) if not gold[l]]
    return "".join("g" if gold[k] else "s" if guess[k] in rest else "-" for k in range(5))


def drive(case_text, io):
    tokens = case_text.split()
    t = int(tokens[0])
    answers = [WORDS[int(x)] for x in tokens[1:1 + t]]
    io.send(str(len(WORDS)))
    io.send(SCRAMBLE)
    io.send(str(t))
    total = 0
    for answer in answers:
        io.send(answer[0])
        for tries in range(5):
            guess = io.recv_line()
            if guess not in VALID:
                io.send("-----")
                break
            m = marks(guess, answer)
            io.send(m)
            if m == "ggggg":
                total += POINTS[tries]
                break
    if total < 98 * t:
        raise RuntimeError(f"average score {total / t:.3f} < 98")


if __name__ == "__main__":
    run_interactor(drive)
