"""Check the repository against plan/LAYOUT.md and gen.toml; write REPO.md.

    uv run python scripts/repo-layout.py --check   fail on drift (commit tier, via gen.py)
    uv run python scripts/repo-layout.py --write   rewrite REPO.md from plan/LAYOUT.md

Fails when a tracked top-level path is not in plan/LAYOUT.md, when a file
headed "Generated by ..." matches no `files` pattern in gen.toml, when a
gen.toml pattern matches no tracked file, or when REPO.md is stale.
"""
import fnmatch
import re
import subprocess
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LAYOUT = ROOT / "plan" / "LAYOUT.md"
HEADER = re.compile(r"[Gg]enerated (?:by|from)\b[^\n]*(?:scripts/|\.mjs|tree-sitter|just )")
TEXT = {".md", ".txt", ".json", ".mdx", ".c", ".toml", ".cp", ".yml"}


def tracked():
    out = subprocess.run(["git", "ls-files", "-z"], cwd=ROOT, capture_output=True, check=True).stdout
    return [p for p in out.decode().split("\0") if p and (ROOT / p).exists()]


def sections(text):
    """(heading, [(paths, job)]) for every table in the layout."""
    out, head = [], None
    for line in text.splitlines():
        if line.startswith("## "):
            head = line[3:]
            out.append((head, []))
        elif head and line.startswith("| `"):
            cells = [c.strip() for c in line.strip("|").split("|")]
            out[-1][1].append((re.findall(r"`([^`]+)`", cells[0]), cells[1]))
    return out


def top(path):
    return path.strip("/").split("/")[0]


def render(secs):
    lines = ["# REPO.md", "",
             "Generated by `scripts/repo-layout.py` from `plan/LAYOUT.md`; edit that file instead.",
             "Where everything lives: one line per top-level path.", "",
             "| Path | Holds |", "|---|---|"]
    for head, rows in secs:
        if head == "Root":
            lines += [f"| {', '.join(f'`{p}`' for p in paths)} | {job} |" for paths, job in rows]
        elif head.startswith("`"):
            name, _, job = head.partition(":")
            job = job.strip().rstrip(".")
            lines.append(f"| {name.strip()} | {job[:1].upper() + job[1:]}. |")
    return "\n".join(lines) + "\n"


def main(argv):
    text = LAYOUT.read_text()
    secs = sections(text)
    want = render(secs)
    if "--write" in argv:
        (ROOT / "REPO.md").write_text(want)
        print("repo-layout: wrote REPO.md")
        return 0
    errors = []
    named = {top(p) for head, rows in secs for paths, _ in rows for p in paths if head != "Moves"}
    named |= {top(h.split("`")[1]) for h, _ in secs if h.startswith("`")}
    files = tracked()
    for t in sorted({top(p) for p in files} - named):
        errors.append(f"top-level `{t}` is not in plan/LAYOUT.md")
    pats = [pat for e in tomllib.loads((ROOT / "gen.toml").read_text())["gen"] for pat in e["files"]]
    owned = lambda p: any(fnmatch.fnmatch(p, pat) or fnmatch.fnmatch(p, pat.replace("**/", "")) for pat in pats)
    for p in files:
        if Path(p).suffix not in TEXT or p.startswith(("corpus/submissions/", "research/archive/")):
            continue
        try:
            head = (ROOT / p).read_text(errors="ignore")[:600]
        except OSError:
            continue
        if HEADER.search(head) and not owned(p):
            errors.append(f"{p} says it is generated but no gen.toml entry owns it")
    for pat in pats:
        if not any(fnmatch.fnmatch(p, pat) or fnmatch.fnmatch(p, pat.replace("**/", "")) for p in files):
            errors.append(f"gen.toml pattern `{pat}` matches no tracked file")
    if (ROOT / "REPO.md").read_text() != want:
        errors.append("REPO.md is stale; run: uv run python scripts/repo-layout.py --write")
    for e in errors:
        print(f"repo-layout: {e}")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
