#!/usr/bin/env python3
"""Check that named arguments in spec/core and spec/lib code blocks exist in std.

For every call `f(..., k: v)` in a fenced block where some `fn f` is declared in
std, `k` must be a parameter of at least one std `fn f`. Calls to names that
std does not declare (user fns, records, constructors) are not checked.
Known mismatches live in spec/conformance/sig-gaps.txt, which may only shrink.

Usage: scripts/conformance-sigs.py [--check | --update]
"""
import glob, os, re, sys
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GAPS = os.path.join(ROOT, "spec/conformance/sig-gaps.txt")


def balanced(text, i):
    """Return the text inside the parens opening at text[i] == '('."""
    depth = 0
    for j in range(i, len(text)):
        c = text[j]
        if c in "([{":
            depth += 1
        elif c in ")]}":
            depth -= 1
            if depth == 0:
                return text[i + 1 : j]
    return None


def top_level_parts(s, angle=False):
    opens, closes = ("([{<", ")]}>") if angle else ("([{", ")]}")
    parts, depth, cur, prev = [], 0, "", ""
    for c in s:
        arrow = c == ">" and prev in "=-"
        prev = c
        if c in opens:
            depth += 1
        elif c in closes and not arrow:
            depth -= 1
        if c == "," and depth == 0:
            parts.append(cur)
            cur = ""
        else:
            cur += c
    parts.append(cur)
    return [p.strip() for p in parts if p.strip()]


def std_params():
    params = defaultdict(set)
    for path in glob.glob(os.path.join(ROOT, "std/*.cp")):
        text = open(path).read()
        for m in re.finditer(r"\bfn\s+(\w+)\s*(<[^(]*>)?\s*\(", text):
            inner = balanced(text, m.end() - 1)
            if inner is None:
                continue
            names = params[m.group(1)]
            names.add("")
            for p in top_level_parts(inner, angle=True):
                n = re.match(r"(?:mut\s+)?(\w+)\s*[:=]", p)
                if n:
                    names.add(n.group(1))
    return params


def blocks(path):
    lines = open(path).read().split("\n")
    i = 0
    while i < len(lines):
        if re.match(r"^\s*```(cp|python)\s*$", lines[i]):
            start, body = i + 1, []
            i += 1
            while i < len(lines) and not re.match(r"^\s*```\s*$", lines[i]):
                body.append(lines[i])
                i += 1
            yield start, "\n".join(body)
        i += 1


def mismatches():
    params = std_params()
    out = set()
    for path in sorted(glob.glob(os.path.join(ROOT, "spec/core/*.md")) + glob.glob(os.path.join(ROOT, "spec/lib/*.md"))):
        rel = os.path.relpath(path, os.path.join(ROOT, "spec"))
        for _, body in blocks(path):
            code = re.sub(r"//[^\n]*", "", body)
            for m in re.finditer(r"(\.?)\b(\w+)\s*\(", code):
                name = m.group(2)
                if name not in params or re.search(r"\b(fn|law)\s+$", code[: m.start()][-8:]):
                    continue
                inner = balanced(code, m.end() - 1)
                if inner is None:
                    continue
                for p in top_level_parts(inner):
                    k = re.match(r"(\w+):(?!:)", p)
                    if k and k.group(1) not in params[name]:
                        out.add(f"{rel}: {m.group(1)}{name}({k.group(1)}:)")
    return out


def main():
    found = mismatches()
    known = set()
    if os.path.exists(GAPS):
        known = {l.strip() for l in open(GAPS) if l.strip() and not l.startswith("#")}
    if "--update" in sys.argv:
        with open(GAPS, "w") as f:
            f.write("# Named arguments in spec/core and spec/lib that no std fn of that name takes.\n")
            f.write("# Generated by scripts/conformance-sigs.py --update; may only shrink.\n")
            f.writelines(l + "\n" for l in sorted(found))
        print(f"wrote {len(found)} sig gaps")
        return 0
    new = sorted(found - known)
    print(f"sig gaps: {len(found)} ({len(new)} new, {len(known - found)} fixed)")
    for l in new:
        print("  new:", l)
    if "--check" in sys.argv and (new or known - found):
        if known - found:
            print("fixed gaps still listed; run --update")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
