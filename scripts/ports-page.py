#!/usr/bin/env python3
"""ports-page.py: regenerate research/PORTS.md, the newest ports first.

Each row links the CP Lang program, the accepted C++ it was ported from, the
statement and the friction report, with contestant-token counts against the
C++ (library code stripped). Dates are when the port was first committed.
"""
import os, re, subprocess, sys

sys.path.insert(0, os.path.dirname(__file__))
import scoreboard as sb

OUT = os.path.join(sb.ROOT, "research", "PORTS.md")
SHOWN = 60


def added_dates():
    log = subprocess.run(
        ["git", "log", "--diff-filter=A", "--format=@%aI", "--name-only", "--", "proto/ports"],
        cwd=sb.ROOT, capture_output=True, text=True, check=True).stdout
    dates, day = {}, None
    for line in log.splitlines():
        if line.startswith("@"):
            day = line[1:]
        elif line.endswith(".cp"):
            dates.setdefault(line, day)
    return dates


def statement_url(name):
    m = re.fullmatch(r"cf(\d+)([a-z]\d*)", name)
    if m:
        return f"https://codeforces.com/contest/{m[1]}/problem/{m[2].upper()}"
    m = re.fullmatch(r"(a[bgr]c)(\d+)([a-z])", name)
    if m:
        return f"https://atcoder.jp/contests/{m[1]}{m[2]}/tasks/{m[1]}{m[2]}_{m[3]}"
    return None


def friction(name):
    path = os.path.join(sb.FRICTIONS_DIR, f"{name}.md")
    if not os.path.isfile(path):
        return None, None, 0
    text = sb._read_text(path)
    title = re.search(r"(?m)^# \S+\s*[—-]\s*(.+)$", text)
    items, _ = sb.parse_friction_file(path)
    heads = [re.sub(r"^\d+\.\s*", "", it["title"]) for it in items]
    return (title[1].strip() if title else None), (heads[0] if heads else None), len(heads)


def cell(s, n=90):
    s = (s or "").replace("|", "\\|").replace("\n", " ")
    return s if len(s) <= n else s[: n - 1] + "…"


def main():
    dates = added_dates()
    ports = sb.discover_ports()
    rows = []
    for p in ports:
        title, top, count = friction(p["name"])
        tok = sb.measure_tokens(p)
        rows.append((dates.get(p["path"], "uncommitted"), p, title, top, count, tok))
    rows.sort(key=lambda r: (r[0], r[1]["name"]), reverse=True)
    ratios = sorted(r[5]["stripped_token_ratio"] for r in rows if r[5]["stripped_token_ratio"])
    median = ratios[len(ratios) // 2] if ratios else None
    out = [
        "# Ports",
        "",
        "Generated by `scripts/ports-page.py`; do not edit by hand. The newest",
        f"{min(SHOWN, len(rows))} of {len(rows)} ports, each differential-tested against the accepted C++",
        "by `proto/ports/<group>/gate.sh`. Tokens are contestant-written: the port",
        "against the original with its library code stripped"
        + (f" (median {median:.2f}x, goal at most 0.6x)." if median else "."),
        "",
        "| Added | Problem | Port | Tokens | Frictions | First friction |",
        "|---|---|---|---|---|---|",
    ]
    for day, p, title, top, count, tok in rows[:SHOWN]:
        url = statement_url(p["name"])
        prob = f"[{p['name']}]({url})" if url else p["name"]
        if title:
            prob += f" {cell(title, 40)}"
        port = f"[.cp](../{p['path']}) · [C++](../{p['orig_path']})"
        ratio = tok["stripped_token_ratio"] or tok["token_ratio"]
        toks = f"{tok['cp_tokens']} ({ratio:.2f}x)" if ratio else str(tok["cp_tokens"])
        fr = f"[{count}](frictions/{p['name']}.md)" if count else "–"
        out.append(f"| {day[:10]} | {prob} | {port} | {toks} | {fr} | {cell(top)} |")
    open(OUT, "w").write("\n".join(out) + "\n")
    print(f"wrote {os.path.relpath(OUT, sb.ROOT)}: {len(rows)} ports")


if __name__ == "__main__":
    main()
