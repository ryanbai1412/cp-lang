"""Generate spec/conformance/ownership/: where a lent view may be kept.

Crosses the source of a view (a named local, an unnamed temporary, a lent
parameter), the storage that keeps it (`let`, `var`, a push into a local
list, an assignment into a local `var`, a push into a `mut` parameter), the
order of storage and source, and the scope (file body or fn body). The
expected verdict comes from the rules, computed here, not from the compiler:

- R05.7.8: storage may keep a lent value if it dies no later than every
  source, so storage declared before its source can't (E0603);
- R05.7.9: storage reached through a parameter is the caller's (E0603);
- R05.7.10: the file body is a block like any fn body;
- R07.5.10: an unnamed temporary dies at the end of its statement (E0603).

Enforces handbook/guidelines/conformance-checklist.md#conformancer5-where-a-rule-covers-a-space-generate-the-cases
"""
from __future__ import annotations

import specgate
from specgate import Problem

HELP = "spec/conformance/ownership/ crosses where a lent view may be kept, generated (--write regenerates)"
GEN = "Generated by `scripts/spec-gate.py ownership --write`; edit scripts/specgate/ownership.py, not this file."
LIST = "var ps: List<List<Int>> = []"


def case(source, storage, scope):
    view = "[3, 1, 2].sorted()[0..2]" if source == "temp" else "a[0..2]"
    decl = ["var a = [3, 1, 2]"] if source == "named" else []
    kind, _, order = storage.partition("-")
    store = {"let": [], "var": [], "push": [LIST], "assign": ["var w = [0]"], "out": []}[kind]
    keep = {"let": f"let w = {view}", "var": f"var w = {view}", "push": f"ps.push({view})",
            "assign": f"w = {view}", "out": f"ps.push({view})"}[kind]
    use = "print(ps[0].sum())" if kind == "push" else "print(w.sum())"
    body = (store + decl if order == "before" else decl + store) + [keep] + ([] if kind == "out" else [use])
    params = (["mut ps: List<List<Int>>"] if kind == "out" else []) + (["a: List<Int>"] if source == "param" else [])
    args = (["mut ps"] if kind == "out" else []) + (["[3, 1, 2]"] if source == "param" else [])
    if scope == "fn":
        pre = [LIST] if kind == "out" else []
        lines = [f"fn run({', '.join(params)}):"] + ["    " + b for b in body] + pre + [f"run({', '.join(args)})"]
        if kind == "out":
            lines.append("print(ps.len)")
    else:
        lines = body
    at = lines.index(next(l for l in lines if l.strip() == keep))
    if source == "temp":
        verdict, rule, why = "E0603", "07.5.10 05.7.8", "an unnamed temporary dies at the end of its statement"
    elif kind == "out":
        verdict, rule, why = "E0603", "05.7.9", "storage reached through a parameter is the caller's"
    elif order == "before":
        verdict, rule, why = "E0603", "05.7.8", "storage declared before its source dies after it"
    else:
        verdict, rule, why = "ok", "05.7.8", "the storage dies no later than its source"
    if scope == "top":
        rule += " 05.7.10"
    head = '// expect: ok, output "4"' if verdict == "ok" else "// expect: E0603"
    if verdict != "ok":
        lines[at] += " // <- here"
    return "\n".join([head, f"// rule: {rule}", f"// A {source} source kept by `{keep.split(' = ')[0] if kind in ('let', 'var') else keep.split('(')[0] + '(...)' if kind != 'assign' else 'w = ...'}` in a {scope} body: {why}. {GEN}"] + lines) + "\n"


def cases():
    out = {}
    for scope in ("top", "fn"):
        for source in ("named", "temp", "param"):
            if source == "param" and scope == "top":
                continue
            for storage in ("let", "var", "push-after", "push-before", "assign-after", "assign-before", "out"):
                if storage.endswith("before") and source != "named":
                    continue
                if storage == "out" and scope == "top":
                    continue
                out[f"{scope}-{source}-{storage}.cp"] = case(source, storage, scope)
    return out


def args(p) -> None:
    p.add_argument("--write", action="store_true")


def run(a) -> list[Problem]:
    return specgate.sync(specgate.CONFORMANCE / "ownership", cases(), a.write, "ownership")
