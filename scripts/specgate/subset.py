"""`spec/SUBSET.md` is generated: its sections from the spec, its gaps from the cases.

Each rule section of `core/` and `tools/` and each `conformance/std-*`
family is a row. A row's status (`supported`, `documented`, `gap`) and a
non-supported row's note are the only hand-kept cells; a new section
starts `supported`. The known-gap list is every case's `// gap:` line, so
no one edits a shared list. `--write` regenerates the file.
"""
from __future__ import annotations

import re
from collections import Counter

import specgate
from specgate import Problem
from specgate.gaps import all_gaps

HELP = "spec/SUBSET.md is what the spec sections and the cases' `// gap:` lines generate"
SUBSET = specgate.ROOT / "spec" / "SUBSET.md"
SPEC = specgate.ROOT / "spec"
RULE_DEF = re.compile(r"\(R((?:\d\d[a-z]?|[a-z]+)(?:\.\d+)+)(, permits)?\)")
STATUSES = ("supported", "documented", "gap")
PREAMBLE = """# The Milestone 1 subset

What CP Lang promises for Milestone 1 (`handbook/product/milestones.md`): a
contestant who has never used it learns, solves, tests and submits with it,
unaided. Each rule section of `core/` and `tools/` is one row:

- *supported*: promised. Every conformance case citing it passes, except the
  known gaps below.
- *documented*: specified, not promised for the milestone; it may work.
- *gap*: not usable yet as a whole; the note names the owner.

Generated by `scripts/spec-gate.py subset --write`: only a row's status and
a non-supported row's note are edited here. A known gap is a
`// gap: <owner> <YYYY-MM-DDTHHZ>` line in its case (`spec-gate.py gaps`
holds the lines to the suite, `spec-gate.py gap-age` fails one past 48 h).

Library families are rows too, one per `conformance/std-*` folder
(`std-heap` is every case there). The contest staples (heaps, graphs and
trees, DSU, prefix sums, Fenwick and segment trees, sequences, strings,
grids, modular math, I/O, search and DP) are supported; the rest are
documented.

`Rlsp` cases drive `cpl lsp --stdio` (`tools-lsp/`); the LSP's own suites go deeper (`tools/lsp.md`).
"""


def section_of(rid: str) -> str:
    parts = rid.split(".")
    return parts[0] if not parts[0][:1].isdigit() else ".".join(parts[:2])


def sections() -> dict[str, str]:
    out = {}
    for path in sorted((SPEC / "core").glob("*.md")) + sorted((SPEC / "tools").glob("*.md")):
        heading = path.stem
        for line in path.read_text().split("\n"):
            if line.startswith("#"):
                heading = line.lstrip("#").strip()
            for m in RULE_DEF.finditer(line):
                out.setdefault(section_of(m.group(1)), heading)
    for fam in sorted(d for d in specgate.CONFORMANCE.glob("std-*") if d.is_dir() and any(d.glob("*.cp"))):
        out[fam.name] = f"library: {fam.name[4:]}"
    return out


def label(k: str) -> str:
    return k if k.startswith("std-") else f"R{k}"


def key_order(k: str):
    return (0, k.split(".")[0].zfill(3), int(k.split(".")[1])) if "." in k else (1, k, 0)


def kept_rows(text: str) -> dict[str, tuple[str, str]]:
    rows = {}
    for line in text.split("\n"):
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) >= 3 and cells[2] in STATUSES and (cells[0].startswith("R") or cells[0].startswith("std-")):
            key = cells[0][1:] if cells[0].startswith("R") else cells[0]
            rows[key] = (cells[2], cells[3] if len(cells) > 3 else "")
    return rows


def case_sections(case: str, text_of) -> set[str]:
    out = set()
    if case.startswith("std-"):
        out.add(case.split("/")[0])
    for line in text_of(case).split("\n")[1:8]:
        s = line.strip()
        if s.startswith("//") and s[2:].strip().startswith("rule:"):
            out |= {section_of(r) for r in s[2:].strip()[5:].split()}
    return out


def generate(old: str) -> str:
    rows, secs, gaps = kept_rows(old), sections(), all_gaps()
    text_of = lambda c: (specgate.CONFORMANCE / c).read_bytes().decode()
    per = Counter(s for c in gaps for s in case_sections(c, text_of))
    out = [PREAMBLE, "## Sections", "", "| Section | Heading | Status | Note |", "|---|---|---|---|"]
    for k in sorted(secs, key=key_order):
        st, note = rows.get(k, ("supported", ""))
        if st == "supported":
            note = f"{per[k]} known gap{'s' * (per[k] != 1)}" if per[k] else ""
        out.append(f"| {label(k)} | {secs[k]} | {st} | {note} |")
    out += ["", "## Known gaps", ""]
    for c, (line, p) in sorted(gaps.items()):
        out.append(f"- {c}: {line.removeprefix('// gap: ')}")
    if not gaps:
        out.append("None.")
    return "\n".join(out) + "\n"


def args(p):
    p.add_argument("--write", action="store_true", help="regenerate spec/SUBSET.md")


def run(a) -> list[Problem]:
    old = SUBSET.read_text() if SUBSET.exists() else ""
    rows = kept_rows(old)
    problems = [Problem(f"spec/SUBSET.md {label(k)}", "is a `gap` row with no owner in its note")
                for k, (st, note) in rows.items() if st == "gap" and not note]
    new = generate(old)
    if new != old:
        if a.write:
            SUBSET.write_text(new)
        else:
            problems.append(Problem("spec/SUBSET.md", "is stale; run `scripts/spec-gate.py subset --write`"))
    return problems
