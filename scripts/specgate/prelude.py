"""R11.3.2: every pub fn in a spec/lib chapter's tables is a prelude name.

A table entry is a top-level `fn name` line in a fenced block of spec/lib/*.md,
or a Markdown table row starting with a `name(...)` cell, whose name std
declares as a top-level `pub fn`. Each must be imported by std/prelude.cp.
(`scripts/spec-gate.py std-docs` checks the other way: prelude names against
the chapters.) Known misses live in spec/conformance/prelude-gaps.txt, which
may only shrink: `--write` rewrites it and refuses to add a line.
Rule: handbook/process/quality.md#which-test-to-write.
Enforces handbook/guidelines/conformance-checklist.md#conformancer5-where-a-rule-covers-a-space-generate-the-cases
"""
from __future__ import annotations

import re

import specgate
from specgate import Problem

HELP = "every spec/lib table fn std declares is a prelude name; prelude-gaps.txt only shrinks (--write)"
HEAD = ("# Table fns of spec/lib chapters that std/prelude.cp does not import (R11.3.2).\n"
        "# Generated by `scripts/spec-gate.py prelude --write`; may only shrink.\n")


def args(p) -> None:
    p.add_argument("--write", action="store_true")


def prelude_names(root) -> set[str]:
    names: set[str] = set()
    for group in re.findall(r"use std\.\w+\.\{([^}]*)\}", (root / "std/prelude.cp").read_text()):
        names.update(re.findall(r"\b\w+\b", group))
    return names


def std_pub_fns(root) -> set[str]:
    return {n for p in root.glob("std/*.cp") for n in re.findall(r"^pub fn (\w+)", p.read_text(), re.M)}


def table_fns(text: str):
    for body in re.findall(r"^```(?:cp|python)\s*\n(.*?)^```", text, re.S | re.M):
        yield from re.findall(r"^fn (\w+)", body, re.M)
    yield from re.findall(r"^\| `(\w+)[(<]", text, re.M)


def misses(root) -> set[str]:
    have, pub = prelude_names(root), std_pub_fns(root)
    return {f"{p.relative_to(root)}: {name}" for p in sorted(root.glob("spec/lib/*.md"))
            for name in table_fns(p.read_text()) if name in pub and name not in have}


def run(a) -> list[Problem]:
    root = specgate.ROOT
    gaps = specgate.CONFORMANCE / "prelude-gaps.txt"
    found = misses(root)
    known = {l.strip() for l in gaps.read_text().splitlines() if l.strip() and not l.startswith("#")} if gaps.exists() else set()
    new = [Problem(l.split(": ")[0], f"`{l.split(': ')[1]}` is a table fn std/prelude.cp does not import") for l in sorted(found - known)]
    if new or not a.write:
        return new + [Problem("spec/conformance/prelude-gaps.txt", f"`{l}` is fixed; run: uv run scripts/spec-gate.py prelude --write")
                      for l in sorted(known - found)]
    if found:
        specgate.write(gaps, HEAD + "".join(l + "\n" for l in sorted(found)))
    elif gaps.exists():
        gaps.unlink()
    return []
