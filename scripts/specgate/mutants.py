"""Mutation score: plant small bugs in the compiler, run the suite.

Each mutant is one seeded edit at one line of compiler `src/` (the crates
conformance-bugcatch.py reverts): a comparison loosened or flipped, `&&`
for `||`, `+ 1` for `- 1`, `true` for `false`. It is applied alone in a
scratch worktree at HEAD; `cpl` is rebuilt and the conformance suite rerun.
A mutant is caught when a case that passes at HEAD fails. Mutants that
don't build are unviable and not scored. The bug-catch rate measures bugs
that once happened; this measures bugs that haven't yet.
Enforces handbook/guidelines/conformance-checklist.md#conformancer9-the-suite-catches-bugs-no-past-fix-shows
"""
import os
import random
import re
import shutil
from pathlib import Path

import specgate
from specgate import Problem

HELP = "plant one-line compiler mutants and write the mutation score; --min fails below it (slow)"
ROOT = specgate.ROOT
from specgate import bugcatch as bc

OPS = [
    (re.compile(r" < "), " <= "),
    (re.compile(r" <= "), " < "),
    (re.compile(r" > "), " >= "),
    (re.compile(r" >= "), " > "),
    (re.compile(r" == "), " != "),
    (re.compile(r" != "), " == "),
    (re.compile(r" && "), " || "),
    (re.compile(r" \|\| "), " && "),
    (re.compile(r" \+ 1\b"), " - 1"),
    (re.compile(r" - 1\b"), " + 1"),
    (re.compile(r"\btrue\b"), "false"),
    (re.compile(r"\bfalse\b"), "true"),
]


def sites():
    """Every (file, line, op) a mutant can take, outside test modules and comments."""
    out = []
    for src in bc.SRC:
        for f in sorted((specgate.ROOT / src).rglob("*.rs")):
            for i, line in enumerate(f.read_text().splitlines()):
                if "#[cfg(test)]" in line:
                    break
                code = line.split("//", 1)[0]
                if not code.strip() or '"' in code or "assert" in code:
                    continue
                for k, (pat, _) in enumerate(OPS):
                    if pat.search(code):
                        out.append((f.relative_to(specgate.ROOT).as_posix(), i, k))
    return out


def mutate(wt, path, i, k):
    p = wt / path
    lines = p.read_text().split("\n")
    pat, rep = OPS[k]
    before = lines[i]
    lines[i] = pat.sub(rep, before, count=1)
    p.write_text("\n".join(lines))
    return before.strip(), lines[i].strip()


def args(ap) -> None:
    ap.add_argument("--n", type=int, default=20)
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--min", type=float, help="fail if the score is below this (0..1)")
    ap.add_argument("--work", default=str(ROOT.parent / "cpl-mutants"))
    ap.add_argument("--out", default=str(ROOT / "plan/domains/spec/mutants.md"))


def run(a) -> list[Problem]:
    work = Path(a.work)
    wt = work / "tree"
    work.mkdir(parents=True, exist_ok=True)
    if wt.exists():
        bc.git("worktree", "remove", "--force", str(wt), check=False)
        shutil.rmtree(wt, ignore_errors=True)
    head = bc.git("rev-parse", "HEAD").stdout.strip()
    bc.git("worktree", "prune")
    bc.git("worktree", "add", "--detach", str(wt), "HEAD")
    env = dict(os.environ, CARGO_TARGET_DIR=str(work / "target"))
    pool = sites()
    picked = random.Random(a.seed).sample(pool, min(a.n, len(pool)))
    rows = []
    try:
        base = bc.run_suite(wt, env, work / "base.json")
        if base is None or base is bc.HUNG:
            return [Problem("HEAD", "does not build or the suite hangs")]
        for path, i, k in picked:
            bc.git("checkout", "-f", "-q", head, cwd=wt)
            was, now = mutate(wt, path, i, k)
            # Rebuilds cpl-conform too, so the compiler it links has the mutant.
            got = bc.run_suite(wt, env, work / "mut.json")
            if got is None:
                res, broke = "unviable", []
            else:
                broke = bc.broken(base, got)
                res = "caught" if broke else "missed"
            rows.append((path, i + 1, was, now, res, broke))
            print(f"{path}:{i + 1} {res} ({len(broke)} cases)", flush=True)
    finally:
        bc.git("checkout", "-f", "-q", head, cwd=wt)
        bc.git("worktree", "remove", "--force", str(wt), check=False)
    caught = sum(r[4] == "caught" for r in rows)
    missed = sum(r[4] == "missed" for r in rows)
    score = caught / (caught + missed) if caught + missed else None
    pct = "n/a" if score is None else f"{100 * score:.0f}%"
    lines = [
        "# Mutation score",
        "",
        f"Generated by `uv run scripts/spec-gate.py mutants --n {a.n} --seed {a.seed}` at `{head[:9]}`:",
        f"{len(rows)} one-line mutants of compiler `src/`, drawn from {len(pool)} sites, each applied alone",
        "and the conformance suite rerun. Caught = a case that passes at HEAD fails.",
        "",
        f"**{caught} of {caught + missed} viable mutants caught ({pct})**; {len(rows) - caught - missed} don't build.",
        "",
        "A missed mutant is a change to the compiler no case notices: either a case is missing,",
        "or the mutated code has no effect a program can see (an equivalent mutant).",
        "",
        "| site | was | mutant | result | cases that fail |",
        "|---|---|---|---|---|",
    ]
    for path, line, was, now, res, broke in rows:
        cell = lambda s: "`" + s.replace("|", "\\|").replace("`", "'")[:70] + "`"
        lines.append(f"| `{path}:{line}` | {cell(was)} | {cell(now)} | {res} | {len(broke)} |")
    Path(a.out).write_text("\n".join(lines) + "\n")
    print(f"mutants: {pct} ({caught} caught, {missed} missed, {len(rows) - caught - missed} unviable)")
    if a.min is not None and (score is None or score < a.min):
        return [Problem(a.out, f"mutation score {pct} is below {a.min:.0%}")]
    return []
