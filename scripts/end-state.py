"""Write plan/END-STATE.md: every suite of the end state, where it stands and what is left.

    uv run python scripts/end-state.py           write it
    uv run python scripts/end-state.py --check [--against REF]   fail if it is stale or plan/end-state.toml is wrong (the ratchet's `end_state_broken`)

Reads `plan/end-state.toml` (the suites, their sizes, properties and targets) and
`scripts/debt-ratchet.json` (each number as the gate last measured it).
"""
import json
import subprocess
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "plan" / "end-state.toml"
RATCHET = ROOT / "scripts" / "debt-ratchet.json"
OUT = ROOT / "plan" / "END-STATE.md"
# Suites are added, never dropped: removing one would lower `end_state_unmeasured` for free.
SUITES_AT_LEAST = 25
FIELDS = ("id", "group", "name", "decides", "size", "properties", "level")


def cell(v):
    return str(v).replace("|", "\\|").replace("\n", " ").strip()


def load():
    """The suites and what is wrong with the file."""
    suites = tomllib.loads(SOURCE.read_text(encoding="utf-8"))["suite"]
    counts = json.loads(RATCHET.read_text(encoding="utf-8"))
    errors = []
    if len(suites) < SUITES_AT_LEAST:
        errors.append(f"{len(suites)} suites, and there were {SUITES_AT_LEAST}: a suite is finished, not removed")
    for i, s in enumerate(suites, 1):
        where = f"suite {s.get('id', '?')}"
        errors += [f"{where}: no `{f}`" for f in FIELDS if not s.get(f)]
        if s.get("id") != i:
            errors.append(f"{where}: ids run 1, 2, 3, ... in order; this is number {i}")
        if not s.get("numbers") and not s.get("missing"):
            errors.append(f"{where}: needs `numbers` (debt-ratchet counters) or `missing` (what would count it)")
        for n in s.get("numbers", []):
            if not isinstance(counts.get(n["counter"]), int):
                errors.append(f"{where}: `{n['counter']}` is not a counter in scripts/debt-ratchet.json")
            if n["target"] != 0:
                errors.append(f"{where}: `{n['counter']}` targets {n['target']}; a ratchet counter ends at 0")
    return suites, counts, errors


GUARDED = ("name", "decides", "size", "properties", "level", "numbers", "missing")


def retargeted(before, now):
    """Suites of `before` that are gone from `now`, or whose name, target, size, property,
    numbers or `missing` differ with no new `changed` note on the suite."""
    errors = []
    by_id = {s["id"]: s for s in now}
    for old in before:
        new = by_id.get(old["id"])
        if new is None:
            errors.append(f"suite {old['id']} ({old['name']}) is gone: a suite is finished, not removed")
            continue
        moved = [k for k in GUARDED if old.get(k) != new.get(k)]
        if moved and new.get("changed") in (None, "", old.get("changed")):
            errors.append(f"suite {old['id']}: {', '.join(moved)} changed with no new "
                          '`changed = "<date>: <why>"` on the suite')
    return errors


def suites_at(ref):
    """The suites as `ref` has them, or none when it has no such file."""
    out = subprocess.run(["git", "show", f"{ref}:plan/end-state.toml"], cwd=ROOT, capture_output=True, text=True)
    return tomllib.loads(out.stdout)["suite"] if out.returncode == 0 else []


def state(suite, counts):
    """`done`, `measured` or `unmeasured`, and each number as `name now -> target`."""
    numbers = [(n["counter"], counts.get(n["counter"]), n["target"]) for n in suite.get("numbers", [])]
    shown = ", ".join(f"`{c}` {now:,} → {target:,}" for c, now, target in numbers)
    if suite.get("missing"):
        return "unmeasured", "; ".join(x for x in (shown, f"no number yet for: {suite['missing']}") if x)
    return ("done" if all(now == target for _, now, target in numbers) else "measured"), shown


def render(suites, counts):
    states = [state(s, counts) for s in suites]
    tally = {k: sum(1 for st, _ in states if st == k) for k in ("done", "measured", "unmeasured")}
    out = [
        "# End state",
        "",
        "Generated by `scripts/end-state.py` from `plan/end-state.toml` and `scripts/debt-ratchet.json`;",
        "edit the first, and the gate measures the second. The migration to the new architecture",
        "(`handbook/design/architecture.md`) is done when every suite here is `done`.",
        "",
        f"**{tally['done']} of {len(suites)} suites done; {tally['measured']} measured and not there; "
        f"{tally['unmeasured']} with no number yet.**",
        "",
        "- `done`: every number is at its target.",
        "- `measured`: the gate counts it, and the count only moves toward the target.",
        "- `unmeasured`: nothing counts it yet. Building its number comes before building toward it.",
        "",
        "Rules for every suite: expected results come from the spec, never from what a compiler",
        "prints; a case passes, is wrong, or is refused (not implemented), and a refusal is never",
        "a correct rejection; a committed list is always what the suite finds; each suite is itself",
        "measured, by a mutation score or a matrix with no empty cell.",
    ]
    group = None
    for s, (st, numbers) in zip(suites, states):
        if s["group"] != group:
            group = s["group"]
            out += ["", f"## {group}", "", "| # | Suite | State | Numbers, now → target |", "|---|---|---|---|"]
        out.append(f"| {s['id']} | {cell(s['name'])} | {st} | {cell(numbers)} |")
    left = sorted((n, v) for n, v in counts.items() if n.startswith("next_") and isinstance(v, int) and v > 0)
    out += ["", "## New-pipeline debt left", "",
            "Each gated `next_*` counter still above 0. The stage-5 switch lands only when this",
            "list is empty (`handbook/design/next/migration.md` rule 14); "
            "`debt-ratchet.py --zero --prefix next_` checks it.", ""]
    out += ["| Counter | Now |", "|---|---|", *(f"| `{n}` | {v:,} |" for n, v in left)] if left else ["None."]
    out += ["", "## What each suite must be", ""]
    for s in suites:
        out += [f"### {s['id']}. {s['name']}", "",
                f"- Decides: {s['decides']}.",
                f"- Minimum size: {s['size']}.",
                f"- At the end state: {s['properties']}.",
                f"- Mechanism level (`handbook/process/quality.md`): {s['level']}."]
        out += [f"- Last changed: {s['changed']}."] if s.get("changed") else []
        out.append("")
    return "\n".join(out)


def main():
    suites, counts, errors = load()
    args = sys.argv[1:]
    if "--against" in args:
        errors += retargeted(suites_at(args[args.index("--against") + 1]), suites)
    if errors:
        print("\n".join(f"end-state: {e}" for e in errors))
        return 1
    text = render(suites, counts)
    if "--check" in sys.argv[1:]:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != text:
            print("plan/END-STATE.md is stale; run: uv run python scripts/end-state.py")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
