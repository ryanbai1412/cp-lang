#!/usr/bin/env python3
# Enforces handbook/design/sources-of-truth.md#never-written-twice
"""Write spec/lints.md, the table of every lint, from spec/lints/*/lint.toml
and spec/checker-lints/*/lint.toml. `--check` fails if the file is stale."""
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "spec/lints.md"


def render() -> str:
    rows: dict[str, tuple[list[str], str]] = {}
    for sub in ("spec/lints", "spec/checker-lints"):
        for path in sorted((ROOT / sub).glob("*/lint.toml")):
            lint = tomllib.loads(path.read_text(encoding="utf-8"))
            names, summary = rows.setdefault(lint["code"], ([], lint.get("summary", "")))
            names.append(path.parent.name)
    lines = [
        "# Lints",
        "",
        "Generated by scripts/gen-lint-table.py from each lint's `lint.toml` under",
        "`spec/lints/` (`cpl lint`) and `spec/checker-lints/` (`cpl check`); edit",
        "those, then run `just gen`. `cpl explain <code>` prints a lint's page.",
        "",
        "| Code | Name | Fires on |",
        "|---|---|---|",
    ]
    for code in sorted(rows):
        names, summary = rows[code]
        lines.append(f"| {code} | {' / '.join(names)} | {summary.replace('|', '\\|')} |")
    return "\n".join(lines) + "\n"


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != text:
            print("spec/lints.md is stale: run scripts/gen-lint-table.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
