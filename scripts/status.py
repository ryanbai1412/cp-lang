"""Write plan/STATUS.md: every domain's metrics and the open questions.

    uv run python scripts/status.py           write it (`just status`)
    uv run python scripts/status.py --check   fail if it is stale (commit tier, via gen.py)

Reads `plan/domains/*/metrics.toml` (the recorded `today`, not a fresh run;
each metric's `command` re-measures it) and the "Open" section of
`plan/QUESTIONS.md`, and counts `Skipped: <process>, <reason>` commit trailers per
lane per day from git history.
"""
import collections
import importlib.util
import json
import re
import subprocess
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "plan" / "STATUS.md"


def cell(v):
    return str(v).replace("|", "\\|").replace("\n", " ").strip()


def usecase_rows():
    spec = importlib.util.spec_from_file_location("check_usecases", ROOT / "scripts" / "check-usecases.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    entries, _, state = mod.load(ROOT)
    return mod.table(entries, state)


SKIPPED_HEAD = "## Skipped process (`Skipped:` trailers per lane per day)"


def skipped_table(log: str) -> list[str]:
    """`log` is `date\x1fdomain\x1fskipped` per commit; one row per day and lane."""
    counts = collections.Counter()
    for line in log.split("\n"):
        day, lane, skipped = (line.split("\x1f") + ["", ""])[:3]
        n = len([s for s in skipped.split("\x1e") if s.strip()])
        if n:
            counts[(day, lane.strip() or "none")] += n
    rows = [f"| {day} | {cell(lane)} | {n} |" for (day, lane), n in sorted(counts.items(), key=lambda kv: (kv[0][0], kv[0][1]), reverse=True)]
    return ["| Day | Lane | Skipped |", "|---|---|---|", *rows] if rows else ["None."]


def written_skipped_table(text: str) -> list[str]:
    """The table under SKIPPED_HEAD in a STATUS.md already written, without its intro."""
    section = text.split(f"\n{SKIPPED_HEAD}\n", 1)[1:]
    lines = section[0].split("\n## ", 1)[0].splitlines() if section else []
    start = next((i for i, l in enumerate(lines) if l.startswith("| Day ") or l == "None."), None)
    if start is None:
        return ["None."]
    table = lines[start:]
    return table[:table.index("")] if "" in table else table


def skipped_rows() -> list[str]:
    """From git history; a shallow clone keeps the table already written."""
    git = lambda *a: subprocess.run(["git", *a], cwd=ROOT, capture_output=True, text=True, check=False).stdout
    if git("rev-parse", "--is-shallow-repository").strip() != "false":
        return written_skipped_table(OUT.read_text() if OUT.exists() else "")
    return skipped_table(git("log", "--date=short", "--format=%ad%x1f%(trailers:key=Domain,valueonly,separator=%x2c)"
                             "%x1f%(trailers:key=Skipped,valueonly,separator=%x1e)"))


def render():
    domains = sorted(p.parent for p in (ROOT / "plan" / "domains").glob("*/metrics.toml") if p.parent.name != "TEMPLATE")
    qs = (ROOT / "plan" / "QUESTIONS.md").read_text()
    open_part = qs.split("\n## Open", 1)[-1].split("\n## ", 1)[0]
    questions = re.findall(r"(?m)^### (.+)$", open_part)
    ratchet = ROOT / "scripts" / "debt-ratchet.json"
    unchecked = json.loads(ratchet.read_text()).get("register_rows_by_domain", {}) if ratchet.is_file() else {}
    out = ["# Status", "",
           "Generated by `scripts/status.py` (`just status`) from `plan/domains/*/metrics.toml` and",
           "`plan/QUESTIONS.md`; edit those instead. Values are as recorded; each metric's",
           "`command` in its `metrics.toml` measures it again. Unchecked rows are quality-register",
           "rows naming no existing check, from `scripts/debt-ratchet.json`; they only go down.", "",
           "Authority: handbook leads design; spec/ is its downstream exhaustive form.", "",
           "| Domain | Metrics | Unchecked rows | Open questions |", "|---|---|---|---|"]
    body = []
    for d in domains:
        name = d.name
        try:
            metrics = tomllib.loads((d / "metrics.toml").read_text()).get("metric", [])
            err = None
        except tomllib.TOMLDecodeError as e:
            metrics, err = [], str(e)
        mine = [q for q in questions if q.split(":")[0].strip() == name]
        out.append(f"| [{name}](domains/{name}/README.md) | {len(metrics) if not err else 'unparsed'} | {unchecked.get(name, '')} | {len(mine)} |")
        body += ["", f"## {name}", ""]
        if err:
            body.append(f"`metrics.toml` does not parse: {cell(err)}")
            continue
        body += ["| Metric | Today | Target |", "|---|---|---|"]
        for m in metrics:
            body.append(f"| {cell(m.get('name', '?'))} | {cell(m.get('today', m.get('value', '?')))} | {cell(m.get('target', ''))} |")
    out += body
    out += ["", "## Use cases (`handbook/product/**/*-usecases.md`)", "",
            "From `scripts/check-usecases.py`. A `supported` or `partial` use case whose Evidence names",
            "nothing runnable counts as a gap. M1 baseline gaps are the M1-critical ones open when the",
            "catalogue was first written and only go down; M1 readiness gaps are every open M1-critical one.", ""]
    out += usecase_rows()
    out += ["", SKIPPED_HEAD, "",
            "Process costing more than 10% of a change is skipped with a trailer",
            "(`handbook/process/handbook-and-rfcs.md`); this counts them.", ""]
    out += skipped_rows()
    out += ["", "## Open questions (`plan/QUESTIONS.md`)", ""] + [f"- {cell(q)}" for q in questions]
    return "\n".join(out) + "\n"


def raises_since(since: str | None) -> list[str]:
    """Each `Raise:` trailer in `since..HEAD`, by default since plan/STATUS.md was last written:
    a baseline raised by the coordinator's sign-off, for the coordinator and the audits to check
    against a ruling."""
    git = lambda *a: subprocess.run(["git", *a], cwd=ROOT, capture_output=True, text=True, check=False).stdout
    since = since or git("log", "-1", "--format=%H", "--", "plan/STATUS.md").strip()
    log = git("log", "--no-merges", "--format=%h%x1f%(trailers:key=Raise,valueonly,separator=%x1e)",
              f"{since}..HEAD" if since else "HEAD")
    return [f"{sha} Raise: {r.strip()}" for sha, _, rs in (l.partition("\x1f") for l in log.splitlines())
            for r in rs.split("\x1e") if r.strip()]


def main(argv):
    if "--raises" in argv:
        i = argv.index("--raises")
        found = raises_since(argv[i + 1] if i + 1 < len(argv) else None)
        print("\n".join(found) if found else "status: no baseline raised")
        return 0
    text = render()
    if "--check" in argv:
        if not OUT.exists() or OUT.read_text() != text:
            print("plan/STATUS.md is stale; run: just status")
            return 1
        return 0
    OUT.write_text(text)
    print(f"status: wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
