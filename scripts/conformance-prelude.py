#!/usr/bin/env python3
"""Check R11.3.2: every pub fn in a spec/lib chapter's tables is a prelude name.

A table entry is a top-level `fn name` line in a fenced block of spec/lib/*.md
whose name spec/std declares as a top-level `pub fn`. Each must be imported by
spec/std/prelude.cp. (`scripts/spec-stub.py --check` checks the other way:
prelude names against the chapters.) Known misses live in
spec/conformance/prelude-gaps.txt, which may only shrink.

Usage: scripts/conformance-prelude.py [--check | --update]
"""
import glob, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GAPS = os.path.join(ROOT, "spec/conformance/prelude-gaps.txt")


def prelude_names():
    text = open(os.path.join(ROOT, "spec/std/prelude.cp")).read()
    names = set()
    for group in re.findall(r"use std\.\w+\.\{([^}]*)\}", text):
        names.update(re.findall(r"\b\w+\b", group))
    return names


def std_pub_fns():
    names = set()
    for path in glob.glob(os.path.join(ROOT, "spec/std/*.cp")):
        names.update(re.findall(r"^pub fn (\w+)", open(path).read(), re.M))
    return names


def table_fns(path):
    text = open(path).read()
    for body in re.findall(r"^```(?:cp|python)\s*\n(.*?)^```", text, re.S | re.M):
        yield from re.findall(r"^fn (\w+)", body, re.M)


def misses():
    have, pub = prelude_names(), std_pub_fns()
    found = set()
    for path in sorted(glob.glob(os.path.join(ROOT, "spec/lib/*.md"))):
        chapter = os.path.relpath(path, ROOT)
        for name in table_fns(path):
            if name in pub and name not in have:
                found.add(f"{chapter}: {name}")
    return found


def main():
    found = misses()
    known = set()
    if os.path.exists(GAPS):
        known = {l.strip() for l in open(GAPS) if l.strip() and not l.startswith("#")}
    if "--update" in sys.argv:
        with open(GAPS, "w") as f:
            f.write("# Table fns of spec/lib chapters that spec/std/prelude.cp does not import (R11.3.2).\n")
            f.write("# Generated by scripts/conformance-prelude.py --update; may only shrink.\n")
            f.writelines(l + "\n" for l in sorted(found))
        print(f"wrote {len(found)} prelude gaps")
        return 0
    new = sorted(found - known)
    print(f"prelude gaps: {len(found)} ({len(new)} new, {len(known - found)} fixed)")
    for l in new:
        print("  new:", l)
    if "--check" in sys.argv and (new or known - found):
        if known - found:
            print("fixed gaps still listed; run --update")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
