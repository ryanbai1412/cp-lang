#!/usr/bin/env python3
# Enforces handbook/guidelines/conformance-checklist.md#conformancer5-where-a-rule-covers-a-space-generate-the-cases
"""Generate spec/conformance/widths/: `Int` arithmetic at every width boundary.

Crosses the operators `+ - * / %` (as expressions and as compound
assignments) and unary `-` with boundary operands: 0, +-1, 2, +-(2^63 - 1)
(the `Int` range; -2^63 is the `None` niche, R03.3.3), their neighbours,
2^62 and the square-root boundary 3037000499/3037000500. Operands pass
through a fn so nothing is proven in range (R03.4.2). Expected results come
from R03.4.1's table, computed here, not from the compiler:

- checked build: an in-range result prints; an out-of-range result traps
  with R0202 on its line;
- `with checks(overflow: off)`: the result wraps to 64 bits (a wrap that
  lands on -2^63 may read as `None`, so those are left out).

Division and remainder are Euclidean (R02); a zero divisor is left out.

    uv run scripts/conformance-widths.py [--check]
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "spec" / "conformance" / "widths"
MAX = 2**63 - 1
VALUES = [0, 1, -1, 2, MAX, -MAX, MAX - 1, -MAX + 1, 2**62, 3037000499, 3037000500, -3037000500]
OPS = {"add": "+", "sub": "-", "mul": "*", "div": "/", "rem": "%"}
TRAPS_PER_OP = 6
HEAD = "// rule: 03.4.1 03.4.2\n// Generated by scripts/conformance-widths.py; edit the script, not this file.\n"
ID = "fn id(k: Int) -> Int = k\n"


def ediv(a, b):
    r = a % abs(b)
    return (a - r) // b, r


def exact(op, a, b):
    if op in ("div", "rem") and b == 0:
        return None
    return {"add": lambda: a + b, "sub": lambda: a - b, "mul": lambda: a * b,
            "div": lambda: ediv(a, b)[0], "rem": lambda: ediv(a, b)[1]}[op]()


def wrap(x):
    x &= 2**64 - 1
    return x - 2**64 if x >= 2**63 else x


def lit(v):
    return f"id({v})" if v >= 0 else f"id(-{-v})"


def cases():
    out = {}
    for op, sym in OPS.items():
        ok, wrapped, traps = [], [], []
        for a in VALUES:
            for b in VALUES:
                r = exact(op, a, b)
                if r is None:
                    continue
                if -MAX <= r <= MAX:
                    ok.append((a, b, r))
                else:
                    traps.append((a, b))
                if wrap(r) != -2**63:
                    wrapped.append((a, b, wrap(r)))
        body = "".join(f"print({lit(a)} {sym} {lit(b)})\n" for a, b, _ in ok)
        out[f"{op}-in-range.cp"] = (f'// expect: ok, output "{chr(92)}n".join(...)', ok, body)
        out[f"{op}-in-range.cp"] = (
            "// expect: ok, output \"" + "\\n".join(str(r) for *_, r in ok) + "\"\n" + HEAD
            + f"// `{sym}` on every in-range pair of boundary operands.\n" + ID + body)
        body = "with checks(overflow: off):\n" + "".join(
            f"    print({lit(a)} {sym} {lit(b)})\n" for a, b, _ in wrapped)
        out[f"{op}-wraps-when-unchecked.cp"] = (
            "// expect: ok, output \"" + "\\n".join(str(r) for *_, r in wrapped) + "\"\n" + HEAD
            + f"// `{sym}` wraps to 64 bits on every boundary pair once overflow checks are off.\n"
            + ID + body)
        step = max(1, len(traps) // TRAPS_PER_OP)
        for i, (a, b) in enumerate(traps[::step][:TRAPS_PER_OP]):
            out[f"{op}-traps-{i}.cp"] = (
                "// expect: R0202 at 4 (checked)\n" + HEAD
                + f"// {a} {sym} {b} is outside `Int`, so a checked build traps.\n" + ID
                + f"print({lit(a)} {sym} {lit(b)})\n")
            out[f"{op}-assign-traps-{i}.cp"] = (
                "// expect: R0202 at 5 (checked)\n" + HEAD
                + f"// {a} {sym}= {b} is outside `Int`, so a checked build traps.\n" + ID
                + f"var t = {lit(a)}\nt {sym}= {lit(b)}\nprint(t)\n")
    neg = [v for v in VALUES]
    out["neg-in-range.cp"] = (
        "// expect: ok, output \"" + "\\n".join(str(-v) for v in neg) + "\"\n" + HEAD
        + "// Unary `-` of every boundary operand stays in `Int`: the range is symmetric.\n"
        + ID + "".join(f"print(-{lit(v)})\n" for v in neg))
    return out


def main() -> int:
    want = cases()
    have = {p.name: p.read_text() for p in OUT.glob("*.cp")} if OUT.exists() else {}
    if "--check" in sys.argv:
        stale = sorted(set(want) ^ set(have) | {k for k in want if have.get(k) != want[k]})
        for name in stale:
            print(f"spec/conformance/widths/{name}: stale; run scripts/conformance-widths.py")
        return 1 if stale else 0
    OUT.mkdir(exist_ok=True)
    for name in set(have) - set(want):
        (OUT / name).unlink()
    for name, text in want.items():
        (OUT / name).write_text(text)
    print(f"{len(want)} cases in spec/conformance/widths/")
    return 0


if __name__ == "__main__":
    sys.exit(main())
