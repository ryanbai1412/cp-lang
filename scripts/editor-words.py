"""Write editors/words.json: the reserved and literal words of
crates/cpl-syntax/src/token.rs (`KEYWORDS`, `LITERAL_WORDS`), which the
tree-sitter grammar and the JetBrains plugin read instead of keeping a list.

    uv run python scripts/editor-words.py           rewrite it
    uv run python scripts/editor-words.py --check   fail if it is stale
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "editors/words.json"


def words():
    token = (ROOT / "crates/cpl-syntax/src/token.rs").read_text()
    table = lambda head: re.findall(r'"(\w+)"', token.split(head, 1)[1].split("];", 1)[0])
    return {"keywords": table("pub const KEYWORDS: [&str;"), "literals": table("pub const LITERAL_WORDS: &[&str] = &[")}


def main(argv):
    text = "// Generated by scripts/editor-words.py from crates/cpl-syntax/src/token.rs; `just gen` rewrites it.\n"
    text = json.dumps({"//": text.strip("/ \n"), **words()}, indent=2) + "\n"
    if "--check" in argv:
        if not OUT.exists() or OUT.read_text() != text:
            print("editors/words.json is stale; run: just gen")
            return 1
        return 0
    OUT.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
