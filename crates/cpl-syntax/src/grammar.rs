//! The highlighting grammars of editors without a language server, generated
//! from the lexer's own tables ([`KEYWORDS`], [`LITERAL_WORDS`]) so none can
//! drift from the compiler. `cpl setup` writes them; with `cpl lsp` running,
//! its semantic tokens replace them.

use crate::{KEYWORDS, LITERAL_WORDS};

/// The reserved words that are not literal values.
fn keywords() -> impl Iterator<Item = &'static str> {
    KEYWORDS.into_iter().filter(|k| !LITERAL_WORDS.contains(k))
}

/// Vim's `syntax/cp.vim`.
pub fn vim() -> String {
    let keywords: Vec<&str> = keywords().collect();
    let mut out = String::from(
        "\" CP Lang highlighting, generated by `cpl setup` from crates/cpl-syntax's token tables.\n\
         if exists('b:current_syntax')\n    finish\nendif\n\n",
    );
    for line in keywords.chunks(12) {
        out += &format!("syntax keyword cpKeyword {}\n", line.join(" "));
    }
    out += &format!("syntax keyword cpBoolean {}\n", LITERAL_WORDS.join(" "));
    out += r#"syntax match cpType '\<\u\w*\>'
syntax match cpDecorator '@\h\w*'
syntax match cpLabel "'\h\w*\>'\@!"
syntax match cpNumber '\<0[xX][0-9a-fA-F_]\+\>'
syntax match cpNumber '\<0[bB][01_]\+\>'
syntax match cpNumber '\<\d[0-9_]*\%(\.\d[0-9_]*\)\=\%([eE][+-]\=\d[0-9_]*\)\=\>'
syntax match cpChar "'\%(\\.\|[^\\']\)'"
syntax region cpString start='\<r"' end='"\|$' oneline
syntax region cpString start='"' skip='\\.' end='"\|$' oneline contains=cpEscape,cpInterpolation
syntax match cpEscape '\\.\|{{\|}}' contained
syntax region cpInterpolation matchgroup=cpDelimiter start='{\ze[^{]' end='}' contained contains=TOP oneline
syntax keyword cpTodo TODO FIXME XXX contained
syntax match cpComment '//.*$' contains=cpTodo
syntax match cpDocComment '///.*$' contains=cpTodo

"#;
    for (group, link) in [
        ("Keyword", "Keyword"),
        ("Boolean", "Boolean"),
        ("Type", "Type"),
        ("Decorator", "PreProc"),
        ("Label", "Label"),
        ("Number", "Number"),
        ("Char", "Character"),
        ("String", "String"),
        ("Escape", "SpecialChar"),
        ("Delimiter", "Delimiter"),
        ("Todo", "Todo"),
        ("Comment", "Comment"),
        ("DocComment", "SpecialComment"),
    ] {
        out += &format!("highlight default link cp{group} {link}\n");
    }
    out + "\nlet b:current_syntax = 'cp'\n"
}

/// An Emacs regexp matching exactly one of `words` as a whole symbol.
fn emacs_symbols<'a>(words: impl Iterator<Item = &'a str>) -> String {
    format!("\\_<\\(?:{}\\)\\_>", words.collect::<Vec<_>>().join("\\|"))
}

/// Emacs's font-lock rules, one `read`able list of `font-lock-keywords`.
pub fn emacs() -> String {
    let rules = [
        (emacs_symbols(keywords()), "font-lock-keyword-face"),
        (emacs_symbols(LITERAL_WORDS.iter().copied()), "font-lock-constant-face"),
        ("@[[:alpha:]_][[:alnum:]_]*".into(), "font-lock-preprocessor-face"),
        ("\\_<fn[ \t]+\\([[:alpha:]_][[:alnum:]_]*\\)".into(), "1 font-lock-function-name-face"),
        ("\\_<[[:upper:]][[:alnum:]_]*\\_>".into(), "font-lock-type-face"),
        ("'[[:alpha:]_][[:alnum:]_]*\\_>\\(?:[^']\\|$\\)".into(), "font-lock-constant-face"),
        (
            "\\_<\\(?:0[xX][[:xdigit:]_]+\\|0[bB][01_]+\\|[0-9][0-9_]*\\(?:\\.[0-9][0-9_]*\\)?\\(?:[eE][+-]?[0-9][0-9_]*\\)?\\)\\_>".into(),
            "font-lock-constant-face",
        ),
    ];
    let mut out = String::from(
        ";; Generated by `cpl setup emacs --grammar` from crates/cpl-syntax's token tables.\n(",
    );
    for (regexp, face) in rules {
        let quoted = regexp.replace('\\', "\\\\").replace('"', "\\\"");
        let sep = if face.starts_with(char::is_numeric) {
            " "
        } else {
            " . "
        };
        out += &format!("(\"{quoted}\"{sep}{face})\n ");
    }
    out.truncate(out.trim_end().len());
    out + ")\n"
}

/// The JetBrains plugin's highlighting lexer, editors/lexer.tsv: one `TOKEN<tab>regex`
/// rule per line in Java's regex syntax, tried in order at each offset; the first that
/// matches takes the text. No rule spans a line, so the IDE can relex from any line.
pub fn jetbrains() -> String {
    let word = r"[\p{L}\p{Nd}_]";
    let keyword = format!("(?:{})(?!{word})", KEYWORDS.join("|"));
    let rules = [
        ("WHITE_SPACE", r"[ \t\r\n]+".to_string()),
        ("DOC_COMMENT", r"///(?!/)[^\n]*".into()),
        ("LINE_COMMENT", r"//[^\n]*".into()),
        ("STRING", r#"r"[^"\n]*"?"#.into()),
        ("STRING", r#""(?:\\[^\n]|[^"\n])*"?"#.into()),
        ("CHAR", r"'\\[^\n]'|'[^\n]'".into()),
        ("LABEL", format!(r"'[\p{{L}}_]{word}*")),
        ("DECORATOR", format!(r"@[\p{{L}}_]{word}*")),
        (
            "NUMBER",
            format!(
                r"0[xXbB]{word}*|\p{{Nd}}[\p{{Nd}}_]*(?:\.\p{{Nd}}[\p{{Nd}}_]*)?(?:[eE][+-]?\p{{Nd}}[\p{{Nd}}_]*)?"
            ),
        ),
        ("KEYWORD", keyword),
        ("TYPE_NAME", format!(r"\p{{Lu}}{word}*")),
        ("IDENTIFIER", format!(r"[\p{{L}}_]{word}*")),
        ("COMMA", ",".into()),
        ("DOT", r"\.".into()),
        ("LPAREN", r"\(".into()),
        ("RPAREN", r"\)".into()),
        ("LBRACKET", r"\[".into()),
        ("RBRACKET", r"\]".into()),
        ("LBRACE", r"\{".into()),
        ("RBRACE", r"\}".into()),
        ("OPERATOR", "(?s).".into()),
    ];
    let mut out = String::from(
        "# Generated by `cpl setup jetbrains --grammar` from crates/cpl-syntax's token tables.\n",
    );
    for (token, regex) in rules {
        out += &format!("{token}\t{regex}\n");
    }
    out
}
