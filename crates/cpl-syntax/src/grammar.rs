//! The highlighting grammars of editors without a language server, generated
//! from the lexer's own tables ([`KEYWORDS`], [`LITERAL_WORDS`]) so none can
//! drift from the compiler. `cpl setup` writes them; with `cpl lsp` running,
//! its semantic tokens replace them.

use crate::{TokenKind, KEYWORDS, LITERAL_WORDS};

/// The reserved words that are not literal values.
fn keywords() -> impl Iterator<Item = &'static str> {
    KEYWORDS.into_iter().filter(|k| !LITERAL_WORDS.contains(k))
}

/// Vim's `syntax/cp.vim`.
pub fn vim() -> String {
    let keywords: Vec<&str> = keywords().collect();
    let mut out = String::from(
        "\" CP Lang highlighting, generated by `cpl setup` from crates/cpl-syntax's token tables.\n\
         if exists('b:current_syntax')\n    finish\nendif\n\n",
    );
    for line in keywords.chunks(12) {
        out += &format!("syntax keyword cpKeyword {}\n", line.join(" "));
    }
    out += &format!("syntax keyword cpBoolean {}\n", LITERAL_WORDS.join(" "));
    out += r#"syntax match cpType '\<\u\w*\>'
syntax match cpDecorator '@\h\w*'
syntax match cpLabel "'\h\w*\>'\@!"
syntax match cpNumber '\<0[xX][0-9a-fA-F_]\+\>'
syntax match cpNumber '\<0[bB][01_]\+\>'
syntax match cpNumber '\<\d[0-9_]*\%(\.\d[0-9_]*\)\=\%([eE][+-]\=\d[0-9_]*\)\=\>'
syntax match cpNumber '\.\@1<=\d[0-9_]*'
syntax match cpChar "'\%(\\x\x\x\|\\.\|[^\\']\)'"
syntax region cpString start='\<r"' end='"\|$' oneline
syntax region cpString start='"' skip='\\.' end='"\|$' oneline contains=cpEscape,cpInterpolation
syntax match cpEscape '\\.\|{{\|}}' contained
syntax region cpInterpolation matchgroup=cpDelimiter start='{\ze[^{]' end='}' contained contains=TOP oneline
syntax keyword cpTodo TODO FIXME XXX contained
syntax match cpComment '//.*$' contains=cpTodo
syntax match cpDocComment '///.*$' contains=cpTodo

"#;
    for (group, link) in [
        ("Keyword", "Keyword"),
        ("Boolean", "Boolean"),
        ("Type", "Type"),
        ("Decorator", "PreProc"),
        ("Label", "Label"),
        ("Number", "Number"),
        ("Char", "Character"),
        ("String", "String"),
        ("Escape", "SpecialChar"),
        ("Delimiter", "Delimiter"),
        ("Todo", "Todo"),
        ("Comment", "Comment"),
        ("DocComment", "SpecialComment"),
    ] {
        out += &format!("highlight default link cp{group} {link}\n");
    }
    out + "\nlet b:current_syntax = 'cp'\n"
}

/// An Emacs regexp matching exactly one of `words` as a whole symbol.
fn emacs_symbols<'a>(words: impl Iterator<Item = &'a str>) -> String {
    format!("\\_<\\(?:{}\\)\\_>", words.collect::<Vec<_>>().join("\\|"))
}

/// Emacs's grammar, one `read`able plist: `:font-lock`, the `font-lock-keywords`;
/// `:syntax`, the `(CHAR . DESCRIPTOR)` entries of the mode's syntax table, where
/// operators end a name as the lexer reads them (`impl<S>`, `n=4`); and `:syntactic`,
/// `syntax-propertize-via-font-lock` rules making the quote of a label (`'outer`)
/// punctuation, so only a char literal's quotes pair up.
pub fn emacs() -> String {
    let rules = [
        (emacs_symbols(keywords()), "font-lock-keyword-face"),
        (emacs_symbols(LITERAL_WORDS.iter().copied()), "font-lock-constant-face"),
        ("@[[:alpha:]_][[:alnum:]_]*".into(), "font-lock-preprocessor-face"),
        ("\\_<fn[ \t]+\\([[:alpha:]_][[:alnum:]_]*\\)".into(), "1 font-lock-function-name-face"),
        ("\\_<[[:upper:]][[:alnum:]_]*\\_>".into(), "font-lock-type-face"),
        ("\\('[[:alpha:]_][[:alnum:]_]*\\)\\_>\\(?:[^']\\|$\\)".into(), "1 font-lock-constant-face"),
        (
            "\\(?:^\\|[^.]\\)\\_<\\(0[xX][[:xdigit:]_]+\\|0[bB][01_]+\\|[0-9][0-9_]*\\(?:\\.[0-9][0-9_]*\\)?\\(?:[eE][+-]?[0-9][0-9_]*\\)?\\)\\_>".into(),
            "1 font-lock-constant-face",
        ),
        ("\\.\\([0-9][0-9_]*\\)".into(), "1 font-lock-constant-face"),
    ];
    let quote = |regexp: &str| regexp.replace('\\', "\\\\").replace('"', "\\\"");
    let mut out = String::from(
        ";; Generated by `cpl setup emacs --grammar` from crates/cpl-syntax's token tables.\n(:font-lock\n (",
    );
    for (regexp, face) in rules {
        let sep = if face.starts_with(char::is_numeric) {
            " "
        } else {
            " . "
        };
        out += &format!("(\"{}\"{sep}{face})\n  ", quote(&regexp));
    }
    out.truncate(out.trim_end().len());
    let mut syntax = vec![
        ('/', ". 12"),
        ('\n', ">"),
        ('_', "_"),
        ('\'', "\""),
        ('"', "\""),
    ];
    syntax.extend("+-*%<>=!&|^~?:,.@#$;".chars().map(|c| (c, ".")));
    let syntax: Vec<String> = (syntax.iter())
        .map(|(c, d)| format!("({} . \"{}\")", *c as u32, quote(d)))
        .collect();
    out += &format!(")\n :syntax ({})\n", syntax.join(" "));
    let label = "\\('\\)[[:alpha:]_][[:alnum:]_]+\\_>\\(?:[^']\\|$\\)";
    out + &format!(" :syntactic ((\"{}\" (1 \".\"))))\n", quote(label))
}

/// The editors' highlighting lexer: each token and its regex, tried in order at each
/// offset, the first that matches taking the text. No rule spans a line.
pub fn lexer_rules() -> Vec<(&'static str, String)> {
    let word = r"[\p{L}\p{Nd}_]";
    let keyword = format!("(?:{})(?!{word})", keywords().collect::<Vec<_>>().join("|"));
    let literal = format!("(?:{})(?!{word})", LITERAL_WORDS.join("|"));
    vec![
        ("WHITE_SPACE", r"[ \t\r\n]+".to_string()),
        ("DOC_COMMENT", r"///(?!/)[^\n]*".into()),
        ("LINE_COMMENT", r"//[^\n]*".into()),
        ("STRING", r#"r"[^"\n]*"?"#.into()),
        ("STRING", r#""(?:\\[^\n]|[^"\n])*"?"#.into()),
        ("CHAR", r"'\\x[0-9a-fA-F]{2}'|'\\[^\n]'|'[^\n]'".into()),
        ("LABEL", format!(r"'[\p{{L}}_]{word}*")),
        ("DECORATOR", format!(r"@[\p{{L}}_]{word}*")),
        ("NUMBER", r"(?<=\.)\p{Nd}[\p{Nd}_]*".into()),
        (
            "NUMBER",
            format!(
                r"0[xXbB]{word}*|\p{{Nd}}[\p{{Nd}}_]*(?:\.\p{{Nd}}[\p{{Nd}}_]*)?(?:[eE][+-]?\p{{Nd}}[\p{{Nd}}_]*)?"
            ),
        ),
        ("LITERAL", literal),
        ("KEYWORD", keyword),
        ("TYPE_NAME", format!(r"\p{{Lu}}{word}*")),
        ("IDENTIFIER", format!(r"[\p{{L}}_]{word}*")),
        ("COMMA", ",".into()),
        ("DOT", r"\.".into()),
        ("LPAREN", r"\(".into()),
        ("RPAREN", r"\)".into()),
        ("LBRACKET", r"\[".into()),
        ("RBRACKET", r"\]".into()),
        ("LBRACE", r"\{".into()),
        ("RBRACE", r"\}".into()),
        ("OPERATOR", "(?s).".into()),
    ]
}

/// The JetBrains plugin's highlighting lexer, editors/lexer.tsv: one rule per line, tried
/// in order at each offset, the first that matches taking the text, as five tab-separated
/// fields: the token, its color key (`CP_<key>`), the key's `DefaultLanguageHighlighterColors`
/// default, its name on the color settings page, and the regex as Java reads it. No rule
/// spans a line, so the IDE can relex from any line.
pub fn jetbrains() -> String {
    let mut out = String::from(
        "# Generated by `cpl setup jetbrains --grammar` from crates/cpl-syntax's token tables.\n",
    );
    for (token, key, default, label, regex) in jetbrains_rules() {
        out += &format!("{token}\t{key}\t{default}\t{label}\t{regex}\n");
    }
    out
}

type JetbrainsRule = (
    &'static str,
    &'static str,
    &'static str,
    &'static str,
    String,
);

/// Each of [`lexer_rules`] as the JetBrains plugin colors it: the token, its color key
/// (`-` for none), the key's `DefaultLanguageHighlighterColors` default, its name on the
/// color settings page, and the regex.
fn jetbrains_rules() -> Vec<JetbrainsRule> {
    let mut out = Vec::new();
    for (token, regex) in lexer_rules() {
        let key = match token {
            "WHITE_SPACE" => "-",
            "CHAR" => "STRING",
            "LITERAL" => "KEYWORD",
            "LPAREN" | "RPAREN" => "PARENTHESES",
            "LBRACKET" | "RBRACKET" => "BRACKETS",
            "LBRACE" | "RBRACE" => "BRACES",
            other => other,
        };
        let (default, label) = match key {
            "-" => ("-", "-"),
            "KEYWORD" => ("KEYWORD", "Keyword"),
            "TYPE_NAME" => ("CLASS_NAME", "Type name"),
            "IDENTIFIER" => ("IDENTIFIER", "Identifier"),
            "NUMBER" => ("NUMBER", "Number"),
            "STRING" => ("STRING", "String and char"),
            "LABEL" => ("LABEL", "Label"),
            "LINE_COMMENT" => ("LINE_COMMENT", "Comment"),
            "DOC_COMMENT" => ("DOC_COMMENT", "Doc comment"),
            "DECORATOR" => ("METADATA", "Decorator"),
            "OPERATOR" => ("OPERATION_SIGN", "Operator"),
            "COMMA" => ("COMMA", "Comma"),
            "DOT" => ("DOT", "Dot"),
            "PARENTHESES" => ("PARENTHESES", "Braces and brackets//Parentheses"),
            "BRACKETS" => ("BRACKETS", "Braces and brackets//Brackets"),
            _ => ("BRACES", "Braces and brackets//Braces"),
        };
        out.push((token, key, default, label, regex));
    }
    out
}

/// The Kotlin sources of the JetBrains plugin that are generated from the lexer's rules
/// (decision 611): its build writes them with `cargo run -p cpl-syntax --example jetbrains`.
pub const JETBRAINS_KOTLIN: [&str; 2] = ["CpLexer.kt", "CpHighlighting.kt"];

/// The generated Kotlin source `name`, one of [`JETBRAINS_KOTLIN`].
pub fn jetbrains_kotlin(name: &str) -> Option<String> {
    let template = match name {
        "CpLexer.kt" => include_str!("jetbrains/CpLexer.kt.in"),
        "CpHighlighting.kt" => include_str!("jetbrains/CpHighlighting.kt.in"),
        _ => return None,
    };
    let rules = jetbrains_rules();
    let mut keys = String::new();
    let mut descriptors = String::new();
    let mut calls = String::new();
    let mut colors = String::new();
    let mut braces = String::new();
    let mut seen_keys = Vec::new();
    let mut seen_tokens = Vec::new();
    for (token, key, default, label, regex) in &rules {
        let color = match *key {
            "-" => "null".to_string(),
            _ => format!("COLOR_{key}"),
        };
        if *key != "-" && !seen_keys.contains(key) {
            seen_keys.push(*key);
            keys += &format!(
                "    @JvmField val COLOR_{key} = createTextAttributesKey(\"CP_{key}\", DefaultLanguageHighlighterColors.{default})\n"
            );
            descriptors += &format!(
                "        AttributesDescriptor({}, CpTokens.COLOR_{key}),\n",
                kotlin_str(label)
            );
        }
        calls += &format!(
            "        rule({}, {color}, {}, {}),\n",
            kotlin_str(token),
            kotlin_str(label),
            kotlin_str(regex)
        );
        if seen_tokens.contains(token) {
            continue;
        }
        seen_tokens.push(*token);
        if *key != "-" {
            colors += &format!("        named({}) to COLOR_{key},\n", kotlin_str(token));
        }
        let close = token.strip_prefix('L').map(|rest| format!("R{rest}"));
        if let Some(close) = close.filter(|close| rules.iter().any(|r| r.0 == close)) {
            braces += &format!(
                "        BracePair(CpTokens.named({}), CpTokens.named({}), false),\n",
                kotlin_str(token),
                kotlin_str(&close)
            );
        }
    }
    let header = "// Generated by `cargo run -p cpl-syntax --example jetbrains` from crates/cpl-syntax's\n\
                  // lexer rules (src/grammar.rs, src/jetbrains/). The plugin's build writes it; it is not committed.";
    Some(
        template
            .replace("@HEADER@", header)
            .replace("@KEYS@", &keys)
            .replace("@RULES@", &calls)
            .replace("@COLORS@", &colors)
            .replace("@DESCRIPTORS@", &descriptors)
            .replace("@BRACES@", &braces),
    )
}

/// `text` as a Kotlin string literal.
fn kotlin_str(text: &str) -> String {
    let body = text
        .replace('\\', "\\\\")
        .replace('"', "\\\"")
        .replace('$', "\\$");
    format!("\"{body}\"")
}

/// What every editor grammar must show each token as, by the lexer: the byte offset where
/// each token or comment starts and its class (`comment`, `string`, `char`, `number`,
/// `keyword`, `literal`, `label`, `name` or `punct`), in order.
pub fn classes(text: &str) -> Vec<(usize, &'static str)> {
    let lexed = crate::lex(text);
    let mut out: Vec<(usize, &'static str)> = lexed
        .comments
        .iter()
        .map(|s| (s.start as usize, "comment"))
        .collect();
    for token in &lexed.tokens {
        let word = text
            .get(token.span.start as usize..token.span.end as usize)
            .unwrap_or("");
        if word.trim().is_empty() {
            continue;
        }
        let class = match token.kind {
            _ if LITERAL_WORDS.contains(&word) => "literal",
            TokenKind::Ident => "name",
            TokenKind::Int | TokenKind::Float => "number",
            TokenKind::Str | TokenKind::RawStr => "string",
            TokenKind::Char => "char",
            TokenKind::Label => "label",
            _ if KEYWORDS.contains(&word) => "keyword",
            _ => "punct",
        };
        out.push((token.span.start as usize, class));
    }
    out.sort();
    out
}
