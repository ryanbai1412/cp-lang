//! Single source of truth for every diagnostic code: title, summary, explanation,
//! and verified trigger/fix examples.
//!
//! Used by `cpl explain <CODE>`, `cpl explain --json`, and `site/errors.py`.

use crate::Code;

/// Documentation metadata for one diagnostic code.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub struct CodeInfo {
    pub code: Code,
    pub title: &'static str,
    pub summary: &'static str,
    pub explanation: &'static str,
    pub trigger: &'static str,
    pub fix: &'static str,
    pub mode: &'static str,
}

/// Look up a diagnostic code (e.g. `"E0301"` or `"e0301"`).
pub fn lookup(code: &str) -> Option<&'static CodeInfo> {
    REGISTRY.iter().find(|info| info.code.0.eq_ignore_ascii_case(code))
}

