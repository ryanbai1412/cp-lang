//! Programs nobody wrote: a seeded generator of valid programs for the
//! differential suite (`cpl-conform fuzz`).
//!
//! Every program is valid by construction: it type-checks, never traps,
//! and no `Int` it computes can overflow, because each expression carries
//! a bound on its magnitude and a product is only formed while the bound
//! stays under [`LIMIT`]. Inside a loop, a mutable variable is read only
//! bare (printed or compared), and an assignment's right side uses only
//! immutable names, so a loop can grow a variable by at most its trip
//! count times one step. The same seed always gives the same program.
//! Enforces compiler-changes/R4 in
//! `handbook/guidelines/compiler-changes-checklist.md`.

use std::fmt::Write;

/// Largest magnitude any generated `Int` may reach.
const LIMIT: i128 = 1_000_000_000_000;
/// Bound on a fn parameter; a call's arguments must fit it.
const PARAM: i128 = 1_000;

/// SplitMix64: small, seedable and the same on every platform.
struct Rng(u64);

impl Rng {
    fn next(&mut self) -> u64 {
        self.0 = self.0.wrapping_add(0x9E37_79B9_7F4A_7C15);
        let mut z = self.0;
        z = (z ^ (z >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
        z = (z ^ (z >> 27)).wrapping_mul(0x94D0_49BB_1331_11EB);
        z ^ (z >> 31)
    }

    fn below(&mut self, n: usize) -> usize {
        (self.next() % n as u64) as usize
    }

    fn range(&mut self, lo: i64, hi: i64) -> i64 {
        lo + (self.next() % (hi - lo + 1) as u64) as i64
    }

    fn chance(&mut self, percent: u64) -> bool {
        self.next() % 100 < percent
    }
}

#[derive(Clone)]
struct IntVar {
    name: String,
    bound: i128,
    mutable: bool,
}

#[derive(Clone)]
struct ListVar {
    name: String,
    len: i128,
    elem: i128,
}

struct Func {
    name: String,
    bound: i128,
}

#[derive(Default)]
struct Scope {
    ints: Vec<IntVar>,
    lists: Vec<ListVar>,
}

struct Gen {
    rng: Rng,
    out: String,
    scopes: Vec<Scope>,
    fns: Vec<Func>,
    next: usize,
    /// Trips of the enclosing loops multiplied: how often a statement runs.
    trips: i128,
    /// Inside a lambda, a comprehension or a fn body: no mutable names.
    pure: usize,
    stmts: usize,
}

/// The program for `seed`.
pub fn program(seed: u64) -> String {
    let mut g = Gen {
        rng: Rng(seed),
        out: format!("// generated by `cpl-conform fuzz`, seed {seed}\n"),
        scopes: vec![Scope::default()],
        fns: Vec::new(),
        next: 0,
        trips: 1,
        pure: 0,
        stmts: 0,
    };
    for _ in 0..g.rng.below(3) {
        g.func();
    }
    let n = 4 + g.rng.below(8);
    for _ in 0..n {
        g.stmt(0);
    }
    g.final_print();
    g.out
}

impl Gen {
    fn fresh(&mut self, prefix: &str) -> String {
        self.next += 1;
        format!("{prefix}{}", self.next)
    }

    fn line(&mut self, indent: usize, text: &str) {
        let _ = writeln!(self.out, "{:width$}{text}", "", width = indent * 4);
    }

    fn ints(&self) -> Vec<IntVar> {
        self.scopes
            .iter()
            .flat_map(|s| s.ints.iter())
            .filter(|v| self.pure == 0 || !v.mutable)
            .cloned()
            .collect()
    }

    fn lists(&self) -> Vec<ListVar> {
        self.scopes
            .iter()
            .flat_map(|s| s.lists.iter())
            .cloned()
            .collect()
    }

    fn bump(&mut self, name: &str, bound: i128) {
        for s in self.scopes.iter_mut().rev() {
            if let Some(v) = s.ints.iter_mut().find(|v| v.name == name) {
                v.bound = v.bound.max(bound);
                return;
            }
        }
    }

    fn func(&mut self) {
        let name = self.fresh("f");
        self.scopes.push(Scope {
            ints: ["a", "b"]
                .iter()
                .map(|p| IntVar {
                    name: p.to_string(),
                    bound: PARAM,
                    mutable: false,
                })
                .collect(),
            lists: Vec::new(),
        });
        self.pure += 1;
        let (body, bound) = self.int(3, 1_000_000, false);
        self.pure -= 1;
        self.scopes.pop();
        self.line(0, &format!("fn {name}(a: Int, b: Int) -> Int = {body}"));
        self.fns.push(Func { name, bound });
    }

    /// An `Int` expression whose magnitude stays under `max`, and its
    /// bound. With `in_loop`, mutable names are left out.
    fn int(&mut self, depth: usize, max: i128, in_loop: bool) -> (String, i128) {
        let max = max.min(LIMIT);
        let vars: Vec<IntVar> = self
            .ints()
            .into_iter()
            .filter(|v| v.bound <= max && !(in_loop && v.mutable))
            .collect();
        let leaf = depth == 0 || self.rng.chance(25);
        if leaf {
            if !vars.is_empty() && self.rng.chance(60) {
                let v = &vars[self.rng.below(vars.len())];
                return (v.name.clone(), v.bound.max(1));
            }
            let k = self.rng.range(-9, 9);
            return (format!("{k}"), 9);
        }
        let d = depth - 1;
        match self.rng.below(12) {
            0 | 1 => {
                let (a, ba) = self.int(d, max / 2, in_loop);
                let (b, bb) = self.int(d, max / 2, in_loop);
                let op = if self.rng.chance(50) { "+" } else { "-" };
                (format!("({a} {op} {b})"), ba + bb)
            }
            2 => {
                let (a, ba) = self.int(d, max.min(1_000_000), in_loop);
                let (b, bb) = self.int(d, (max / ba.max(1)).max(1), in_loop);
                if ba * bb <= max {
                    (format!("({a} * {b})"), ba * bb)
                } else {
                    (a, ba)
                }
            }
            3 => {
                let (a, ba) = self.int(d, max, in_loop);
                let mut k = self.rng.range(-5, 5);
                if k == 0 {
                    k = 3;
                }
                if self.rng.chance(50) {
                    (format!("({a} / {k})"), ba)
                } else {
                    (format!("({a} % {k})"), i128::from(k.abs()))
                }
            }
            4 => {
                let (a, ba) = self.int(d, max, in_loop);
                if self.rng.chance(50) {
                    (format!("-({a})"), ba)
                } else {
                    (format!("abs({a})"), ba)
                }
            }
            5 => {
                let (a, ba) = self.int(d, max, in_loop);
                let (b, bb) = self.int(d, max, in_loop);
                let f = if self.rng.chance(50) { "min" } else { "max" };
                (format!("{f}({a}, {b})"), ba.max(bb))
            }
            6 => {
                let c = self.boolean(d, in_loop);
                let (a, ba) = self.int(d, max, in_loop);
                let (b, bb) = self.int(d, max, in_loop);
                (format!("(if {c}: {a} else: {b})"), ba.max(bb))
            }
            7 | 8 => self.list_int(d, max, in_loop),
            9 if !self.fns.is_empty() => {
                let i = self.rng.below(self.fns.len());
                let (a, _) = self.int(d, PARAM, in_loop);
                let (b, _) = self.int(d, PARAM, in_loop);
                let f = &self.fns[i];
                if f.bound <= max {
                    (format!("{}({a}, {b})", f.name), f.bound)
                } else {
                    (a, PARAM)
                }
            }
            _ => {
                if !vars.is_empty() {
                    let v = &vars[self.rng.below(vars.len())];
                    (v.name.clone(), v.bound.max(1))
                } else {
                    (format!("{}", self.rng.range(-9, 9)), 9)
                }
            }
        }
    }

    /// An `Int` folded from a list: its sum, length, a count, min or max.
    fn list_int(&mut self, d: usize, max: i128, in_loop: bool) -> (String, i128) {
        let (l, len, elem) = self.list(d, in_loop);
        match self.rng.below(5) {
            0 if len * elem <= max => (format!("{l}.sum()"), len * elem),
            1 if len <= max => (format!("{l}.len"), len),
            2 if len <= max => {
                let pred = self.lambda(d, elem, in_loop);
                (format!("{l}.count({pred})"), len)
            }
            3 if elem <= max => {
                let f = if self.rng.chance(50) { "min" } else { "max" };
                let k = self.rng.range(-9, 9);
                (format!("({l}.{f}() ?? {k})"), elem.max(9))
            }
            _ => (format!("{}", self.rng.range(-9, 9)), 9),
        }
    }

    /// A `List<Int>` expression and bounds on its length and elements.
    fn list(&mut self, d: usize, in_loop: bool) -> (String, i128, i128) {
        let lists = self.lists();
        if !lists.is_empty() && self.rng.chance(60) {
            let l = &lists[self.rng.below(lists.len())];
            return (l.name.clone(), l.len, l.elem);
        }
        match self.rng.below(4) {
            0 if !lists.is_empty() => {
                let l = lists[self.rng.below(lists.len())].clone();
                if self.rng.chance(50) {
                    (format!("List({}.rev)", l.name), l.len, l.elem)
                } else {
                    (format!("{}.sorted()", l.name), l.len, l.elem)
                }
            }
            1 if !lists.is_empty() => {
                let l = lists[self.rng.below(lists.len())].clone();
                let p = self.fresh("p");
                self.pure += 1;
                self.scopes.push(Scope {
                    ints: vec![IntVar {
                        name: p.clone(),
                        bound: l.elem,
                        mutable: false,
                    }],
                    lists: Vec::new(),
                });
                let (e, be) = self.int(d.min(2), 1_000_000, true);
                let filter = if self.rng.chance(50) {
                    format!(" if {}", self.boolean(d.min(1), true))
                } else {
                    String::new()
                };
                self.scopes.pop();
                self.pure -= 1;
                (format!("[{e} for {p} in {}{filter}]", l.name), l.len, be)
            }
            2 => {
                let i = self.fresh("i");
                let k = self.rng.range(0, 6);
                self.pure += 1;
                self.scopes.push(Scope {
                    ints: vec![IntVar {
                        name: i.clone(),
                        bound: 6,
                        mutable: false,
                    }],
                    lists: Vec::new(),
                });
                let (e, be) = self.int(d.min(2), 1_000_000, true);
                self.scopes.pop();
                self.pure -= 1;
                (format!("[{e} for {i} in 0..{k}]"), 6, be)
            }
            _ => {
                let n = 1 + self.rng.below(5);
                let mut items = Vec::new();
                let mut bound = 1;
                for _ in 0..n {
                    let (e, b) = self.int(d.min(1), 1_000, in_loop);
                    items.push(e);
                    bound = bound.max(b);
                }
                (format!("[{}]", items.join(", ")), n as i128, bound)
            }
        }
    }

    fn lambda(&mut self, d: usize, elem: i128, in_loop: bool) -> String {
        let p = self.fresh("p");
        self.pure += 1;
        self.scopes.push(Scope {
            ints: vec![IntVar {
                name: p.clone(),
                bound: elem,
                mutable: false,
            }],
            lists: Vec::new(),
        });
        let body = self.boolean(d.min(1), in_loop);
        self.scopes.pop();
        self.pure -= 1;
        format!("{p} => {body}")
    }

    /// A `Bool` expression. A comparison inside a loop may read a
    /// mutable name bare, since comparing can't overflow.
    fn boolean(&mut self, depth: usize, in_loop: bool) -> String {
        let d = depth.saturating_sub(1);
        match self.rng.below(if depth == 0 { 1 } else { 5 }) {
            1 => format!(
                "({} and {})",
                self.boolean(d, in_loop),
                self.boolean(d, in_loop)
            ),
            2 => format!(
                "({} or {})",
                self.boolean(d, in_loop),
                self.boolean(d, in_loop)
            ),
            3 => format!("not ({})", self.boolean(d, in_loop)),
            4 => {
                let (l, _, elem) = self.list(d, in_loop);
                let f = if self.rng.chance(50) { "all" } else { "any" };
                let pred = self.lambda(d, elem, in_loop);
                format!("{l}.{f}({pred})")
            }
            _ => {
                let a = self.operand(d, in_loop);
                let b = self.operand(d, in_loop);
                let op = ["<", "<=", "==", "!=", ">", ">="][self.rng.below(6)];
                format!("({a} {op} {b})")
            }
        }
    }

    /// An `Int` to compare or print: inside a loop, maybe a bare mutable.
    fn operand(&mut self, d: usize, in_loop: bool) -> String {
        if in_loop && self.pure == 0 && self.rng.chance(40) {
            let muts: Vec<IntVar> = self.ints().into_iter().filter(|v| v.mutable).collect();
            if !muts.is_empty() {
                return muts[self.rng.below(muts.len())].name.clone();
            }
        }
        self.int(d, LIMIT, in_loop).0
    }

    fn stmt(&mut self, indent: usize) {
        self.stmts += 1;
        let in_loop = self.trips > 1;
        let deep = indent >= 3 || self.stmts > 60;
        match self.rng.below(10) {
            0 | 1 => {
                let name = self.fresh("v");
                let mutable = self.rng.chance(50);
                let (e, b) = self.int(3, LIMIT / 1_000, in_loop);
                let kw = if mutable { "var" } else { "let" };
                self.line(indent, &format!("{kw} {name} = {e}"));
                self.scopes.last_mut().unwrap().ints.push(IntVar {
                    name,
                    bound: b,
                    mutable,
                });
            }
            2 => {
                let name = self.fresh("l");
                let (e, len, elem) = self.list(2, in_loop);
                let is_name = e.chars().all(|c| c.is_ascii_alphanumeric());
                let e = if is_name { format!("List({e})") } else { e };
                self.line(indent, &format!("let {name} = {e}"));
                self.scopes
                    .last_mut()
                    .unwrap()
                    .lists
                    .push(ListVar { name, len, elem });
            }
            3 | 4 => {
                let muts: Vec<IntVar> = self.ints().into_iter().filter(|v| v.mutable).collect();
                if muts.is_empty() {
                    return self.print(indent, in_loop);
                }
                let v = muts[self.rng.below(muts.len())].clone();
                let room = (LIMIT - v.bound) / self.trips.max(1) / 2;
                let (e, b) = self.int(2, room.max(1), in_loop);
                match self.rng.below(3) {
                    0 => {
                        self.line(indent, &format!("{} = {e}", v.name));
                        self.bump(&v.name, b);
                    }
                    1 => {
                        self.line(indent, &format!("{} += {e}", v.name));
                        self.bump(&v.name, v.bound + b * self.trips);
                    }
                    _ => {
                        self.line(indent, &format!("{} -= {e}", v.name));
                        self.bump(&v.name, v.bound + b * self.trips);
                    }
                }
            }
            5 if !deep => {
                let c = self.boolean(2, in_loop);
                self.line(indent, &format!("if {c}:"));
                self.block(indent + 1);
                if self.rng.chance(50) {
                    self.line(indent, "else:");
                    self.block(indent + 1);
                }
            }
            6 if !deep => {
                let i = self.fresh("i");
                let k = self.rng.range(0, 4);
                self.line(indent, &format!("for {i} in 0..{k}:"));
                self.looped(indent, k, Some(i));
            }
            7 if !deep => {
                let c = self.fresh("c");
                let k = self.rng.range(0, 4);
                self.line(indent, &format!("var {c} = 0"));
                self.line(indent, &format!("while {c} < {k}:"));
                self.line(indent + 1, &format!("{c} += 1"));
                self.looped(indent, k, None);
            }
            _ => self.print(indent, in_loop),
        }
    }

    fn looped(&mut self, indent: usize, k: i64, var: Option<String>) {
        let saved = self.trips;
        self.trips = self.trips.max(1) * i128::from(k.max(1)) + 1;
        self.scopes.push(Scope::default());
        if let Some(i) = var {
            self.scopes.last_mut().unwrap().ints.push(IntVar {
                name: i,
                bound: 4,
                mutable: false,
            });
        }
        let n = 1 + self.rng.below(3);
        for _ in 0..n {
            self.stmt(indent + 1);
        }
        self.scopes.pop();
        self.trips = saved;
    }

    fn block(&mut self, indent: usize) {
        self.scopes.push(Scope::default());
        let n = 1 + self.rng.below(3);
        for _ in 0..n {
            self.stmt(indent);
        }
        self.scopes.pop();
    }

    fn print(&mut self, indent: usize, in_loop: bool) {
        let n = 1 + self.rng.below(3);
        let mut args = Vec::new();
        for _ in 0..n {
            args.push(match self.rng.below(4) {
                0 => format!("yes({})", self.boolean(2, in_loop)),
                1 => self.list(2, in_loop).0,
                _ => self.operand(3, in_loop),
            });
        }
        self.line(indent, &format!("print({})", args.join(", ")));
    }

    fn final_print(&mut self) {
        let names: Vec<String> = self.scopes[0]
            .ints
            .iter()
            .map(|v| v.name.clone())
            .chain(self.scopes[0].lists.iter().map(|l| l.name.clone()))
            .collect();
        if !names.is_empty() {
            self.line(0, &format!("print({})", names.join(", ")));
        }
    }
}
