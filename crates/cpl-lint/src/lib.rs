/// Lints one file. Returns warnings (errors for `deny`), in source order.
///
/// A file with a syntax error gets no lints: what the parser could not read
/// may hold the assignment or the read a lint would say is missing.
pub fn lint(src: &str, config: &Config) -> Vec<Diagnostic> {
    let mut diags = with_parsed(src, |file| lint_file(file, config));
    typed::refine(&mut diags, src);
    recheck::recheck(&mut diags, src);
    diags
}

/// `diags` less the lints at the place of one of `errors`: the error
/// already names that root cause (L0509 beside the E0606 it explains). A lint
/// with a quick fix stays unless the error carries one too.
pub(crate) fn drop_repeats(diags: &mut Vec<Diagnostic>, errors: &[Diagnostic]) {
    diags.retain(|d| {
        !errors.iter().any(|e| {
            e.severity == Severity::Error
                && e.span == d.span
                && e.code != d.code
                && (d.fixes.is_empty() || !e.fixes.is_empty())
        })
    });
}

pub fn lint_parsed(src: &str, items: &[(u32, &ParsedItem)], config: &Config) -> Vec<Diagnostic> {
    lint_file(&File { src, items }, config)
}

fn lint_file(file: &File, config: &Config) -> Vec<Diagnostic> {
    let allows = Allows::collect(file);
    let library = file.top_level().any(|(_, stmt)| stmt.public);
    let mut fns = Fns::default();
    file.walk(&mut fns, |fns, base| fns.base = base);
    let mut findings = allows.unknown;
    findings.extend(rules::run(file, config));

    let mut out: Vec<Diagnostic> = Vec::new();
    for Finding { lint, mut diag } in findings {
        let level = config.level(lint);
        let allowed = allows
            .regions
            .iter()
            .any(|(span, name)| *name == lint.name && span.contains(diag.span));
        let library_only = library && LIBRARY_LOOPS.iter().any(|l| l.code == lint.code);
        if level == Level::Allow || allowed || library_only || fns.defines(lint, &diag, library) {
            continue;
        }
        diag.severity = if level == Level::Deny {
            Severity::Error
        } else {
            Severity::Warning
        };
        diag.match_line_endings(file.src);
        out.push(diag);
    }
    out.sort_by_key(|d| (d.span.start, d.span.end, d.code));
    out.dedup();
    let wide: Vec<_> = out
        .iter()
        .map(|d| {
            (
                d.code,
                d.span,
                d.labels.iter().map(|l| l.span).collect::<Vec<_>>(),
            )
        })
        .collect();
    out.retain(|d| {
        !SUPERSEDED_BY.iter().any(|(inner, outer)| {
            inner.code == d.code
                && wide.iter().any(|(code, span, evidence)| {
                    *code == outer.code
                        && (span.contains(d.span)
                            || d.labels.iter().any(|l| span.contains(l.span))
                            || evidence.iter().any(|e| e.contains(d.span)))
                })
        })
    });
    out
}

/// A finding inside a wider one that rewrites the same code better, inside
/// the wider one's labelled evidence, or whose own evidence is inside it: the wider one is shown alone (`s = s + x`
/// in a loop that is one `sum`; `var found = -1` set by a search loop; the
/// push loop that copies a slice only to sort it and write it back; code
/// inside a hand-written algorithm the std call replaces whole; the cache
/// lookup of a memo `@memo` removes).
const SUPERSEDED_BY: &[(&Lint, &Lint)] = &[
    (&SEARCH_LOOP, &PALINDROME_BY_HAND),
    (&PEEK_THEN_POP, &MONOTONE_STACK_BY_HAND),
    (&COMPOUND_SELF_REF, &LOOP_REDUCTION),
    (&CHMIN_CHMAX_IF, &LOOP_REDUCTION),
    (&SENTINEL_SCALAR, &LOOP_REDUCTION),
    (&SENTINEL_SCALAR, &SEARCH_LOOP),
    (&PUSH_LOOP, &COPY_SORT_WRITEBACK),
    (&VAR_NEVER_REASSIGNED, &SEARCH_LOOP),
    (&REPEATED_LITERAL, &HAND_ROLLED_STRING_ALGO),
    (&MANUAL_MOD_REDUCE, &HAND_ROLLED_STRING_ALGO),
    (&MANUAL_MOD_REDUCE, &FACT_TABLES_BY_HAND),
    (&SPLIT_RANGE_CHECK, &HAND_ROLLED_STRING_ALGO),
    (&SHADOWS_TOP_LEVEL, &SLIDING_MIN_BY_HAND),
    (&LAST_VIA_LEN, &SLIDING_MIN_BY_HAND),
    (&LAST_VIA_LEN, &HAND_ROLLED_PREFIX_SUM),
    (&MAP_CONTAINS_THEN_INDEX, &MEMO_BY_HAND),
];

/// Lints that point to a std structure: a library module is where the
/// loops that build one are written.
const LIBRARY_LOOPS: &[&Lint] = &[
    &HAND_ROLLED_RANGE_TREE,
    &HAND_ROLLED_SIEVE,
    &HAND_ROLLED_PREFIX_SUM,
];

/// Lints whose message names the call to write instead.
const NAME_THE_CALL: &[&Lint] = &[&FREE_FOLD, &HAND_ROLLED_ANSWER_SEARCH];

/// Each fn of a file, so a finding that says "this is `first`" is not
/// reported inside `fn first` itself. In a library module that holds for
/// every lint whose help names the call `first(..)`: the fn is where the
/// library writes the loop the lint teaches.
#[derive(Default)]
struct Fns {
    base: u32,
    spans: Vec<(Span, String)>,
}

impl Visitor for Fns {
    fn stmt(&mut self, stmt: &Stmt) {
        if let StmtKind::Fn(decl) = &stmt.kind {
            let quoted = format!("`{}`", decl.name.text);
            self.spans.push((stmt.span.shift(self.base), quoted));
        }
    }
}

impl Fns {
    fn defines(&self, lint: &Lint, diag: &Diagnostic, library: bool) -> bool {
        let names_call = NAME_THE_CALL.iter().any(|l| l.code == lint.code);
        let named = |quoted: &str| {
            // `count(..)` or the method `xs.count(..)` (decision 53).
            let name = quoted.trim_matches('`');
            let calls =
                |h: &str| h.contains(&format!("`{name}(")) || h.contains(&format!(".{name}("));
            (names_call && diag.message.contains(quoted))
                || (library && diag.help.as_deref().is_some_and(calls))
        };
        self.spans
            .iter()
            .any(|(span, quoted)| span.contains(diag.span) && named(quoted))
    }
}

/// The `with lint(name: allow)` contexts of a file.
struct Allows {
    /// The span each one covers and the lint it turns off.
    regions: Vec<(Span, &'static str)>,
    unknown: Vec<Finding>,
}

impl Allows {
    fn collect(file: &File) -> Allows {
        let mut out = Allows {
            regions: Vec::new(),
            unknown: Vec::new(),
        };
        let mut contexts = Contexts {
            base: 0,
            out: &mut out,
        };
        let mut leading = Vec::new();
        for (base, stmt) in file.top_level() {
            contexts.base = base;
            if matches!(stmt.kind, StmtKind::With { body: None, .. }) {
                leading.push((base, stmt));
            }
            cpl_syntax::visit::walk_stmt(stmt, &mut contexts);
        }
        // A bare line at the top of the file covers the rest of it.
        for (base, stmt) in leading {
            contexts.base = base;
            let start = stmt.span.shift(base).start;
            contexts.allow(stmt, Span::new(start, u32::MAX));
        }
        out
    }
}

/// The `with lint(name: allow)` contexts of a file. (R09.4.4)
struct Contexts<'a> {
    base: u32,
    out: &'a mut Allows,
}

impl Contexts<'_> {
    fn allow(&mut self, stmt: &Stmt, covered: Span) {
        let StmtKind::With { ctx, args, .. } = &stmt.kind else {
            return;
        };
        if ctx.text != "lint" {
            return;
        }
        for arg in args {
            let Some(field) = &arg.name else { continue };
            match any_lint_named(&field.text) {
                Some(name) if matches!(&arg.value.kind, ExprKind::Name(v) if v == "allow") => {
                    self.out.regions.push((covered, name))
                }
                Some(_) => {}
                None => self
                    .out
                    .unknown
                    .push(unknown_lint(&field.text, field.span.shift(self.base))),
            }
        }
    }
}

impl cpl_syntax::visit::Visitor for Contexts<'_> {
    fn block(&mut self, block: &Block) {
        for stmt in &block.stmts {
            if matches!(stmt.kind, StmtKind::With { body: None, .. }) {
                self.allow(stmt, stmt.span.to(block.span).shift(self.base));
            }
        }
    }
    fn stmt(&mut self, stmt: &Stmt) {
        if matches!(stmt.kind, StmtKind::With { body: Some(_), .. }) {
            self.allow(stmt, stmt.span.shift(self.base));
        }
    }
}

fn unknown_lint(name: &str, span: Span) -> Finding {
    let mut diag = Diagnostic::warning(
        UNKNOWN_LINT.code,
        span,
        format!("there is no lint called `{name}`"),
    );
    diag.help = Some(match closest_lint(name) {
        Some(close) => format!("did you mean `{close}`?"),
        None => "`cpl lint --list` prints every lint".to_string(),
    });
    Finding {
        lint: &UNKNOWN_LINT,
        diag,
    }
}

/// The lint name within two edits of `name`, if there is one.
pub(crate) fn closest_lint(name: &str) -> Option<&'static str> {
    let names = LINTS.iter().map(|lint| lint.name);
    names
        .chain(CHECKER_LINTS.iter().map(|lint| lint.name))
        .map(|known| (edit_distance(name, known), known))
        .filter(|(distance, _)| *distance <= 2)
        .min()
        .map(|(_, name)| name)
}

use cpl_diag::edit_distance;

/// The removed spellings the parser offers a rewrite for (`where` as a
/// filter, `--- multitest ---`), applied to a fixed point. Parser recovery
/// guesses, such as an inserted `:`, are not among them.
pub fn fix_removed_syntax(src: &str) -> (String, usize) {
    let mut src = src.to_string();
    let mut total = 0;
    loop {
        let codemods: Vec<_> = cpl_syntax::parse_file(&src)
            .diagnostics
            .into_iter()
            .filter(|d| {
                (d.code == cpl_diag::codes::REMOVED_SYNTAX
                    || (d.code == cpl_diag::codes::UNKNOWN_CHAR
                        && d.message == "CP Lang concatenates with `+`"))
                    && !d.fixes.is_empty()
            })
            .collect();
        let (text, applied) = apply_fixes(&src, &codemods);
        if applied == 0 {
            return (src, total);
        }
        total += applied;
        src = text;
    }
}

/// Type-directed rewrites reported by the checker, applied to a fixed point:
/// removed syntax (such as `Range.lo`/`.hi` -> `.start`/`.end`, leaving user
/// struct fields named `lo`/`hi` untouched) and a getter called with `()`.
pub fn fix_checked_removed_syntax(path: Option<&std::path::Path>, src: &str) -> (String, usize) {
    let mut src = src.to_string();
    let mut total = 0;
    let key = path
        .map(|p| p.to_string_lossy().into_owned())
        .unwrap_or_else(|| "<fix>.cp".to_string());
    let mut db = cpl_check::Database::new();
    loop {
        db.set_file(&key, src.as_str());
        let Some(analysis) = db.analyze(&key) else {
            return (src, total);
        };
        let codemods: Vec<_> = analysis
            .diagnostics
            .iter()
            .filter(|d| {
                [
                    cpl_diag::codes::REMOVED_SYNTAX,
                    cpl_diag::codes::NOT_CALLABLE,
                ]
                .contains(&d.code)
                    && !d.fixes.is_empty()
            })
            .cloned()
            .collect();
        let (text, applied) = apply_fixes(&src, &codemods);
        if applied == 0 {
            return (src, total);
        }
        total += applied;
        src = text;
    }
}

/// What `cpl fix` makes of a source: removed-syntax rewrites (parser, then
/// type-directed checker rewrites), then every lint fix, each to a fixed point.
pub fn fix(src: &str, config: &Config) -> (String, usize) {
    fix_at(None, src, config)
}

/// Like [`fix`], resolving imports relative to `path` when given.
pub fn fix_at(path: Option<&std::path::Path>, src: &str, config: &Config) -> (String, usize) {
    let (mut src, mut total) = fix_removed_syntax(src);
    if !cpl_syntax::parse_file(&src).diagnostics.is_empty() {
        return (src, total);
    }
    let (checked, checked_applied) = fix_checked_removed_syntax(path, &src);
    if checked_applied > 0 {
        src = checked;
        total += checked_applied;
    }
    loop {
        let (text, applied) = apply_fixes(&src, &lint(&src, config));
        if applied == 0 {
            return (src, total);
        }
        total += applied;
        src = text;
    }
}

