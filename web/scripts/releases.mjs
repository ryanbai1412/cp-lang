import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const log = readFileSync('../CHANGELOG.md', 'utf8');
const body = log
  .replace(/^# Changelog\n[\s\S]*?(?=^## )/m, '')
  .replace(/^(#{2,}) /gm, (_, h) => `${h} `)
  .replace(/[{}<>]/g, (c) => `\\${c}`);
mkdirSync('content/docs', { recursive: true });
writeFileSync(
  'content/docs/releases.mdx',
  `---\ntitle: Release notes\ndescription: What changed in each version of CP Lang, generated from CHANGELOG.md.\n---\n\n{/* Generated by scripts/releases.mjs from CHANGELOG.md; edit that file instead. */}\n\n${body}`,
);
console.log(`releases: ${(body.match(/^## /gm) ?? []).length} versions`);
