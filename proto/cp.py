#!/usr/bin/env python3
import sys, os, subprocess
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from cpc.parser import parse, ParseError
from cpc.lexer import LexError
from cpc.compiler import compile_program, CompileError

VERSION = "0.1"
HERE = os.path.dirname(os.path.abspath(__file__))

def compiler_rev():
    try:
        rev = subprocess.run(["git", "-C", HERE, "rev-parse", "--short", "HEAD"], capture_output=True, text=True, check=True).stdout.strip()
        dirty = subprocess.run(["git", "-C", HERE, "status", "--porcelain", "--", "cpc", "cp.py"], capture_output=True, text=True).stdout.strip()
        return rev + ("+dirty" if dirty else "")
    except Exception:
        return "unknown"

def run_pinned(rev, args):
    """Re-run this command with the compiler as of commit `rev`."""
    cache = os.path.expanduser(f"~/.cache/cp/{rev}")
    if not os.path.exists(os.path.join(cache, "proto", "cp.py")):
        os.makedirs(cache, exist_ok=True)
        top = subprocess.run(["git", "-C", HERE, "rev-parse", "--show-toplevel"], capture_output=True, text=True, check=True).stdout.strip()
        arch = subprocess.run(["git", "-C", top, "archive", rev, "proto/cp.py", "proto/cpc"], capture_output=True, check=True).stdout
        subprocess.run(["tar", "-x", "-C", cache], input=arch, check=True)
    os.execvp(sys.executable, [sys.executable, os.path.join(cache, "proto", "cp.py"), *args])

def stamp_source(src_path, src):
    """Record the compiler a file was first built with, so old code can be rebuilt with it later."""
    for line in src.splitlines()[:3]:
        if line.startswith("// cp:"):
            have = line.split()[3] if len(line.split()) > 3 else "?"
            cur = compiler_rev()
            if have.split("+")[0] != cur.split("+")[0]:
                print(f"{src_path}: note: written against compiler {have}, building with {cur} "
                      f"(use --compiler {have.split('+')[0]} to pin)", file=sys.stderr)
            return
    open(src_path, "w").write(f"// cp: {VERSION} {compiler_rev()}\n" + src)

def build(src_path):
    src = open(src_path).read()
    try:
        code, comp = compile_program(parse(src))
    except (ParseError, LexError, CompileError) as e:
        print(f"{src_path}: error: {e}", file=sys.stderr)
        sys.exit(1)
    for line, n in sorted(getattr(comp, "cost_warnings", {}).items()):
        print(f"{src_path}: warning: line {line}: this loop nest can run ~{n:.1e} times at the largest declared input", file=sys.stderr)
    stamp_source(src_path, src)
    return f"// generated by cp {VERSION} ({compiler_rev()})\n" + code, comp

def main():
    args = sys.argv[1:]
    if "--compiler" in args:
        i = args.index("--compiler")
        rev = args[i + 1]
        run_pinned(rev, args[:i] + args[i + 2:])
    if args and args[0] == "version":
        print(f"cp {VERSION} ({compiler_rev()})")
        return
    cmd, path = sys.argv[1], sys.argv[2]
    if cmd in ("test", "doc", "lib-run"):
        # library code (stdlib/, examples/local-lib/) runs in the reference interpreter, cpi
        from cpi import runner
        if cmd == "test":
            only = None
            paths = sys.argv[2:]
            if "-k" in paths:
                i = paths.index("-k")
                only = paths[i + 1]
                paths = paths[:i] + paths[i + 2:]
            sys.exit(1 if runner.run_tests(paths, only) else 0)
        if cmd == "doc":
            print(runner.doc(path))
            return
        runner.run_file(path, sys.stdin.read())
        return
    if cmd == "explain":
        _, comp = build(path)
        seen = set()
        for line, name, ty, cpp in getattr(comp, "reprs", []):
            if (line, name) in seen:
                continue
            seen.add((line, name))
            print(f"line {line:4}  {name:14} {ty:34} -> {cpp}")
        return
    if cmd == "locate":
        locate(path, sys.argv[3], int(sys.argv[4]) if len(sys.argv) > 4 else 200, int(sys.argv[5]) if len(sys.argv) > 5 else 8)
        return
    if cmd == "fntest":
        fntest(path, int(sys.argv[3]) if len(sys.argv) > 3 else 20, int(sys.argv[4]) if len(sys.argv) > 4 else 8)
        return
    if cmd == "stress":
        stress(path, sys.argv[3], int(sys.argv[4]) if len(sys.argv) > 4 else 300,
               int(sys.argv[5]) if len(sys.argv) > 5 else 8)
        return
    code, comp = build(path)
    out = os.path.splitext(path)[0] + ".cpp"
    open(out, "w").write(code)
    if cmd == "checks":
        for line, depth, d in comp.checks:
            print(f"line {line}: {'in loop' if depth else 'top'}: {d}")
    size = len(code.encode())
    print(f"wrote {out} ({size} bytes)", file=sys.stderr)
    if size > 65536:
        sys.exit(f"error: {out} is {size} bytes, over the 64 KB submission limit")
    if size > 49152:
        print(f"warning: {out} is {size} bytes, over 48 KB of the 64 KB limit", file=sys.stderr)

def locate(path, ref_src, seeds=200, max_size=8):
    """Find the smallest failing generated input, then blame the first @brute'd part whose swap fixes it."""
    code, comp = build(path)
    base = os.path.splitext(path)[0]
    open(base + ".cpp", "w").write(code)
    def cc(out, *flags, src=base + ".cpp"):
        r = subprocess.run(["g++", "-std=c++17", "-O2", *flags, "-o", out, src], capture_output=True, text=True)
        if r.returncode:
            print(r.stderr[:2000]); sys.exit(1)
        return out
    gen, ours, ref = cc(base + "_gen", "-DCP_GEN_MODE"), cc(base + "_ours"), cc(base + "_ref", src=ref_src)
    run = lambda exe, inp: subprocess.run([exe], input=inp, capture_output=True, text=True, timeout=20).stdout.split()
    found = None
    for size in range(1, max_size + 1):
        for seed in range(1, seeds + 1):
            g = subprocess.run([gen, str(seed), str(size)], capture_output=True, text=True, timeout=20)
            if g.returncode:
                continue
            if run(ours, g.stdout) != run(ref, g.stdout):
                found = g.stdout
                break
        if found:
            break
    if not found:
        print(f"no mismatch found (sizes 1..{max_size}, {seeds} seeds each)"); return
    print("smallest failing input:\n" + found.strip())
    print("ours:     " + " ".join(run(ours, found)))
    print("expected: " + " ".join(run(ref, found)))
    want = run(ref, found)
    for fast, slow, node in comp.fn_brutes:
        exe = cc(base + "_swap", "-DCP_SWAP_" + fast.cpp)
        if run(exe, found) == want:
            print(f"blame: `{fast.node.name}` (replacing it with @brute `{node.name}` fixes this input)")
            return
    print("no single @brute swap fixes it; the bug is outside the tested parts")

def fntest(path, seeds=20, size=8):
    """Check every `@brute(f) fn g(...)` pair on random arguments, over `seeds` random program inputs."""
    code, comp = build(path)
    if not comp.fn_brutes and not comp.fn_props:
        print("no @brute(f) or @invariant fns with parameters"); sys.exit(1)
    base = os.path.splitext(path)[0]
    open(base + ".cpp", "w").write(code)
    exe = base + "_fntest"
    r = subprocess.run(["g++", "-std=c++17", "-O2", "-DCP_GEN_MODE", "-DCP_FNTEST", "-o", exe, base + ".cpp"], capture_output=True, text=True)
    if r.returncode:
        print(r.stderr[:3000]); sys.exit(1)
    rejected = 0
    for seed in range(1, seeds + 1):
        p = subprocess.run([exe, str(seed), str(size)], capture_output=True, text=True, timeout=20)
        if p.returncode == 4:
            rejected += 1
            continue
        out = p.stdout.split("@@FNTEST\n", 1)[-1]
        if p.returncode:
            print(f"seed {seed}:\n{out}{p.stderr[-2000:]}"); sys.exit(1)
    pairs = ", ".join([f"{f.node.name} vs {g.node.name}" for f, g, _ in comp.fn_brutes] + [f"{n.name} under {k}" for _, k, n in comp.fn_props])
    print(f"fntest OK: {pairs} agree on {seeds - rejected} program inputs x 1000 random calls ({rejected} rejected by where)")

def sh(cmd, inp=None, timeout=10, env=None):
    return subprocess.run(cmd, input=inp, capture_output=True, text=True, timeout=timeout, env=env)

def stress(path, ref_cpp, iters=300, size=8):
    code, comp = build(path)
    base = os.path.splitext(path)[0]
    open(base + ".cpp", "w").write(code)
    for out, flags in ((base + "_bin", ["-O2"]), (base + "_gen", ["-O2", "-DCP_GEN_MODE"])):
        r = sh(["g++", "-std=c++17", *flags, "-o", out, base + ".cpp"], timeout=120)
        if r.returncode:
            print(r.stderr[:3000]); sys.exit(1)
    ref = base + "_ref"
    r = sh(["g++", "-std=c++17", "-O2", "-o", ref, ref_cpp], timeout=120)
    if r.returncode:
        print(r.stderr[:3000]); sys.exit(1)
    ok = rej = 0
    for seed in range(1, iters + 1):
        g = sh([base + "_gen", str(seed), str(size)])
        if g.returncode == 4:
            rej += 1; continue
        a = sh([base + "_bin"], g.stdout)
        b = sh([ref], g.stdout)
        if a.stdout.split() != b.stdout.split() or a.returncode:
            print(f"MISMATCH seed={seed}\ninput:\n{g.stdout}\nours:\n{a.stdout}{a.stderr}\nref:\n{b.stdout}")
            sys.exit(2)
        ok += 1
    print(f"stress OK: {ok} tests agree ({rej} rejected by where)")

if __name__ == "__main__":
    main()
