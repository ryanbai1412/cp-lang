void solve() {
	int arr[5];
	iota(begin(arr), end(arr), 0);
	int q;
	cin >> q;
	while(q--) {
		int a, b;
		cin >> a >> b;
		a--;
		b--;
		swap(arr[a], arr[b]);
	}
	cout << (find(begin(arr), end(arr), 2) - arr) + 1 << endl;
}

