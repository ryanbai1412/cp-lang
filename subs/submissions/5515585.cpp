void solve() {
    int n, k;
    cin >> n >> k;
    int perm[n] {};
    fill(perm + k, perm + n, 1);
    cout << "The bit patterns are" << endl;
    do {
        for (auto& a : perm) {
            cout << (a ^ 1);
        }
        cout << endl;
    } while (next_permutation(perm, perm + n));
}

