"""Generate the Ports Gallery page from research/PORTS.md and dream/*.cp files.

Reads `research/PORTS.md` (generated by `scripts/ports-page.py`) plus live `.cp`,
`dream/<name>.cp`, and original C++ files so readers can compare CP Lang ports,
dream programs, and accepted C++ side by side.
"""

from __future__ import annotations

import html
from pathlib import Path
import re

MAX_GALLERY_CARDS = 16
MAX_CPP_LINES = 140

ROW_RE = re.compile(
    r"^\|\s*(\d{4}-\d{2}-\d{2})\s*\|\s*([^|]+?)\s*\|\s*([^|]+?)\s*\|\s*([^|]+?)\s*\|\s*([^|]+?)\s*\|\s*([^|]*?)\s*\|$",
    re.M,
)
LINK_RE = re.compile(r"\[([^\]]+)\]\(\.\./([^)]+)\)")


def parse_ports_md(repo_root: Path) -> tuple[str, list[dict]]:
    """Parse research/PORTS.md into (summary_line, rows)."""
    md_path = repo_root / "research/PORTS.md"
    if not md_path.is_file():
        return ("", [])
    text = md_path.read_text()
    summary_m = re.search(r"The newest\s+\d+\s+of\s+\d+\s+ports.*?median\s+[0-9.]+x[^)]*\)", text, re.S)
    summary = re.sub(r"\s+", " ", summary_m.group(0)).strip() if summary_m else ""
    summary = re.sub(r"\s*\b(?:by|from)\s+`[^`]*/[^`]*`", "", summary)

    rows: list[dict] = []
    seen: set[str] = set()
    for m in ROW_RE.finditer(text):
        date, prob_col, links_col, tokens_col, fric_col, first_fric = (g.strip() for g in m.groups())
        name_m = re.match(r"\[([^\]]+)\]\(([^)]+)\)\s*(.*)", prob_col)
        if name_m:
            name, prob_url, prob_title = name_m.group(1), name_m.group(2), name_m.group(3).strip()
        else:
            name, prob_url, prob_title = prob_col.strip("` "), "", ""
        links = dict(LINK_RE.findall(links_col))
        cp_rel = links.get(".cp", "")
        cpp_rel = links.get("C++", "")
        dream_rel = links.get("dream", "")
        if not dream_rel and cp_rel:
            cp_p = repo_root / cp_rel
            cand = cp_p.parent / "dream" / f"{cp_p.stem}.cp"
            if cand.is_file():
                dream_rel = str(cand.relative_to(repo_root))
        fric_num = re.sub(r"\[(\d+)\]\([^)]+\)", r"\1", fric_col)
        rows.append(
            dict(
                date=date,
                name=name,
                title=prob_title,
                url=prob_url,
                cp_rel=cp_rel,
                cpp_rel=cpp_rel,
                dream_rel=dream_rel,
                tokens=tokens_col,
                frictions=fric_num,
                first_friction=first_fric,
            )
        )
        seen.add(name)

    # Include any dream.cp whose port is older than the newest 60 in PORTS.md.
    for dream_p in sorted((repo_root / "corpus/problems").glob("*/dream.cp")):
        prob_dir = dream_p.parent
        name = prob_dir.name
        if name in seen:
            continue
        cp_p = prob_dir / "port.cp"
        if not cp_p.is_file():
            continue
        cpp_rel = ""
        for cand_cpp in [
            prob_dir / "orig.cpp",
            repo_root / "corpus/submissions/ecnerwala" / f"{name}.cpp",
        ]:
            if cand_cpp.is_file():
                cpp_rel = str(cand_cpp.relative_to(repo_root))
                break
        rows.append(
            dict(
                date="earlier",
                name=name,
                title="",
                url="",
                cp_rel=str(cp_p.relative_to(repo_root)),
                cpp_rel=cpp_rel,
                dream_rel=str(dream_p.relative_to(repo_root)),
                tokens="—",
                frictions="—",
                first_friction="",
            )
        )
        seen.add(name)

    return summary, rows


def _trim_cpp(src: str) -> tuple[str, bool]:
    lines = src.strip().splitlines()
    if len(lines) <= MAX_CPP_LINES:
        return "\n".join(lines), False
    head = "\n".join(lines[:MAX_CPP_LINES])
    return f"{head}\n// ... ({len(lines) - MAX_CPP_LINES} more lines)", True


def _pick_featured(rows: list[dict]) -> list[dict]:
    with_dream = [r for r in rows if r["dream_rel"]]
    without_dream = [r for r in rows if not r["dream_rel"]]
    featured = with_dream[:MAX_GALLERY_CARDS]
    if len(featured) < MAX_GALLERY_CARDS:
        featured.extend(without_dream[: MAX_GALLERY_CARDS - len(featured)])
    return featured


def render_ports_gallery_html(repo_root: Path, highlight_cp, highlight_cpp) -> str:
    summary, rows = parse_ports_md(repo_root)
    featured = _pick_featured(rows)
    dream_count = sum(1 for r in rows if r["dream_rel"])

    parts: list[str] = [
        "<p>Side-by-side comparison of real validated CP Lang solutions, their "
        "<strong>dream</strong> form (how the solution should read without current language "
        "limits), and the accepted C++ originals. Generated directly from the port corpus.</p>",
    ]
    if summary:
        parts.append(
            f'<p class="ports-summary">{html.escape(summary)} '
            f"· <strong>{dream_count}</strong> with dream programs · "
            f"showing <strong>{len(featured)}</strong> side-by-side below.</p>"
        )

    parts.append(
        '<div class="ports-controls">'
        '<button type="button" class="ports-filter active" data-filter="all">All featured</button>'
        f'<button type="button" class="ports-filter" data-filter="dream">With dream ({min(dream_count, len(featured))})</button>'
        '<input type="search" class="ports-search" placeholder="Filter by problem (e.g. cf2066b)..." aria-label="Filter ports">'
        "</div>"
    )

    parts.append('<div class="ports-gallery" id="ports-gallery">')
    for row in featured:
        name = row["name"]
        cp_src = (repo_root / row["cp_rel"]).read_text().strip() if row["cp_rel"] and (repo_root / row["cp_rel"]).is_file() else ""
        dream_src = (repo_root / row["dream_rel"]).read_text().strip() if row["dream_rel"] and (repo_root / row["dream_rel"]).is_file() else ""
        cpp_raw = (repo_root / row["cpp_rel"]).read_text().strip() if row["cpp_rel"] and (repo_root / row["cpp_rel"]).is_file() else ""
        cpp_src, _ = _trim_cpp(cpp_raw)
        has_dream = "true" if dream_src else "false"
        cols_cls = "ports-compare cols-3" if dream_src else "ports-compare cols-2"
        badge = '<span class="ports-badge dream">has dream</span>' if dream_src else '<span class="ports-badge">port + C++</span>'

        parts.append(
            f'<section class="ports-card" id="port-{html.escape(name)}" '
            f'data-name="{html.escape(name.lower())}" data-dream="{has_dream}">'
            f'<div class="ports-card-head">'
            f'<h3><code>{html.escape(name)}</code> {badge}</h3>'
            f'<span class="ports-meta">{html.escape(row["date"])} · tokens: {html.escape(row["tokens"])}</span>'
            f"</div>"
            f'<div class="{cols_cls}">'
        )
        parts.append(
            '<div class="ports-pane">'
            f'<div class="code-label">CP Lang port ({html.escape(name)}.cp)</div>'
            f'<pre><code class="language-cp">{highlight_cp(cp_src)}</code></pre>'
            "</div>"
        )
        if dream_src:
            parts.append(
                '<div class="ports-pane ports-pane-dream">'
                f'<div class="code-label">Dream (dream/{html.escape(name)}.cp)</div>'
                f'<pre><code class="language-cp">{highlight_cp(dream_src)}</code></pre>'
                "</div>"
            )
        parts.append(
            '<div class="ports-pane">'
            f'<div class="code-label">Accepted C++ ({html.escape(name)}.cpp)</div>'
            f'<pre><code class="language-cpp">{highlight_cpp(cpp_src)}</code></pre>'
            "</div>"
        )
        parts.append("</div></section>")
    parts.append("</div>")

    # Compact index of recent ports from research/PORTS.md
    parts.append('<h2 id="recent-ports">Recent ports index</h2>')
    parts.append(
        "<table><thead><tr><th>Date</th><th>Problem</th><th>Tokens (CP / orig)</th>"
        "<th>Dream</th><th>Frictions</th></tr></thead><tbody>"
    )
    for row in rows[:60]:
        name = row["name"]
        dream_cell = "yes" if row["dream_rel"] else "—"
        label = f'<a href="#port-{html.escape(name)}"><code>{html.escape(name)}</code></a>' if any(
            f["name"] == name for f in featured
        ) else f"<code>{html.escape(name)}</code>"
        parts.append(
            f"<tr><td>{html.escape(row['date'])}</td><td>{label}</td>"
            f"<td>{html.escape(row['tokens'])}</td><td>{dream_cell}</td>"
            f"<td>{html.escape(row['frictions'])}</td></tr>"
        )
    parts.append("</tbody></table>")

    parts.append(
        "<script>(function(){"
        "var root=document.getElementById('ports-gallery');if(!root)return;"
        "var cards=[].slice.call(root.querySelectorAll('.ports-card'));"
        "var btns=[].slice.call(document.querySelectorAll('.ports-filter'));"
        "var q=document.querySelector('.ports-search');var mode='all';"
        "function apply(){var s=(q?q.value:'').trim().toLowerCase();"
        "cards.forEach(function(c){var ok=(mode==='all'||c.dataset.dream==='true')&&(!s||c.dataset.name.indexOf(s)!==-1);"
        "c.style.display=ok?'':'none';});}"
        "btns.forEach(function(b){b.addEventListener('click',function(){mode=b.dataset.filter;"
        "btns.forEach(function(x){x.classList.toggle('active',x===b);});apply();});});"
        "if(q)q.addEventListener('input',apply);"
        "})();</script>"
    )
    return "\n".join(parts)
